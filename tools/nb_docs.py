# ---------------------------------------------------------------------------------------------------------------------
# reading the package
# ---------------------------------------------------------------------------------------------------------------------

def _tree(stem: str) -> ast.Module:
    return ast.parse((PACKAGE / f"{stem}.py").read_text(encoding="utf-8"))


def exported() -> list[tuple[str, str, str]]:
    """Every public name of exakit.nb as (name, module stem, name in that module), in ``__all__``'s order."""
    tree = _tree("__init__")
    names: list[str] = []
    origin: dict[str, tuple[str, str]] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            names = [c.value for c in ast.walk(node.value) if isinstance(c, ast.Constant) and isinstance(c.value, str)]
        elif isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "_LAZY" for t in node.targets):
            for key, value in zip(node.value.keys, node.value.values):           # names loaded on first use
                origin[key.value] = (value.value, key.value)
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
            for alias in node.names:
                origin.setdefault(alias.asname or alias.name, (node.module, alias.name))
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            origin.setdefault(node.name, ("__init__", node.name))
    missing = [name for name in names if name not in origin]
    if missing:
        raise SystemExit(f"nb_docs: exakit.nb exports names this tool cannot find a definition for: {', '.join(missing)}")
    return [(name, *origin[name]) for name in sorted(set(names), key=lambda name: (name.lower(), name))]   # Dataset, dataset: always this order


def _definition(tree: ast.Module, name: str) -> ast.AST | None:
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name:
            return node
    return None


def _signature(prefix: str, node: ast.FunctionDef, *, drop_self: bool = False) -> str:
    args = ast.unparse(node.args)
    if drop_self:
        args = re.sub(r"^(self|cls)(, |$)", "", args)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns is not None else ""
    returns = re.sub(r"^ -> (['\"])(.*)\1$", r" -> \2", returns)           # a forward reference reads as the name
    one_line = f"{prefix}({args}){returns}"
    if len(one_line) <= 100 or not args:
        return one_line
    parts, depth, current = [], 0, ""
    for char in args:                                    # one parameter per line; commas inside brackets stay
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        if char == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += char
    parts.append(current.strip())
    return f"{prefix}(\n" + "".join(f"    {part},\n" for part in parts if part) + f"){returns}"


def _is_property(node: ast.FunctionDef) -> bool:
    return any((isinstance(d, ast.Name) and d.id in ("property", "cached_property")) or
               (isinstance(d, ast.Attribute) and d.attr in ("cached_property",)) for d in node.decorator_list)


# ---------------------------------------------------------------------------------------------------------------------
# a docstring as MDX
# ---------------------------------------------------------------------------------------------------------------------

_CODE_SPAN = re.compile(r"(`[^`\n]+`)")


def _prose(text: str) -> str:
    """One prose line as MDX: ``literal`` becomes `literal`, and what MDX would read as markup is escaped."""
    text = re.sub(r"``([^`]+)``", r"`\1`", text)
    out = []
    for index, part in enumerate(_CODE_SPAN.split(text)):
        if index % 2:                                    # inside backticks: as written
            out.append(part)
            continue
        part = part.replace("\\", "\\\\")
        part = re.sub(r"([{}<>*])", r"\\\1", part)
        part = re.sub(r"(?<![A-Za-z0-9])_|_(?![A-Za-z0-9])", r"\\_", part)      # __all__, _private; not SNAKE_CASE
        out.append(part)
    line = "".join(out)
    if re.match(r"\s*#", line):                          # a comment line is not a heading
        line = line.replace("#", "\\#", 1)
    return line


def _language(lines: list[str]) -> str:
    body = "\n".join(lines)
    if re.search(r"^\s*(\$ |exakit |python3 |uv |bash |curl )", body, re.M):
        return "bash"
    if re.search(r"(^|\s)(import |def |nb\.|exakit_nb\.|[a-z_]+ = |with |for |if |print\()", body) or re.search(r"\w\(", body):
        return "python"
    return "text"


def to_mdx(doc: str) -> str:
    """A docstring as MDX: indented blocks become code fences, the rest is escaped prose."""
    lines = doc.strip("\n").split("\n")
    out: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("    ") and (index == 0 or not lines[index - 1].strip() or (out and out[-1] == "```")):
            block = []
            while index < len(lines) and (lines[index].startswith("    ") or
                                          (not lines[index].strip() and index + 1 < len(lines) and lines[index + 1].startswith("    "))):
                block.append(lines[index][4:] if lines[index].strip() else "")
                index += 1
            while block and not block[-1]:
                block.pop()
            out += [f"```{_language(block)}", *block, "```"]
            continue
        out.append(_prose(line))
        index += 1
    return "\n".join(out).strip() + "\n"


def _summary(doc: str | None) -> str:
    """The first sentence of a docstring, as plain text for a table cell or a page description."""
    if not doc:
        return ""
    first = doc.strip().split("\n\n")[0]
    first = " ".join(part.strip() for part in first.split("\n"))
    match = re.match(r"(.+?[.!?])(\s|$)", first)
    sentence = match.group(1) if match else first
    return re.sub(r"``([^`]+)``", r"`\1`", sentence).strip()


def _plain(text: str) -> str:
    return re.sub(r"`([^`]*)`", r"\1", text)


# ---------------------------------------------------------------------------------------------------------------------
# where a command is used
# ---------------------------------------------------------------------------------------------------------------------

def _usage() -> dict[str, list[str]]:
    """For each exakit.nb name, the kit notebooks whose code calls it (``persona/NN_name``)."""
    used: dict[str, list[str]] = {}
    for source in sorted((ROOT / "notebook" / "notebooks").glob("*/*.py")):
        if source.parent.name.startswith("00_"):
            continue
        label = f"{source.parent.name}/{source.stem}"
        for name in set(re.findall(r"\bnb\.([A-Za-z_][A-Za-z0-9_]*)", source.read_text(encoding="utf-8"))):
            used.setdefault(name, []).append(label)
    return used


# ---------------------------------------------------------------------------------------------------------------------
# the pages
# ---------------------------------------------------------------------------------------------------------------------

def _entry(name: str, node: ast.AST, used: list[str]) -> str:
    out = [f"## nb.{name} [#{name}]", ""]
    doc = ast.get_docstring(node)
    if isinstance(node, ast.ClassDef):
        bases = [ast.unparse(base) for base in node.bases]
        kind = "exception" if any(base.endswith(("Exception", "Error")) for base in bases) else "class"
        out += ["```python", f"{kind} nb.{name}", "```", ""]
        if doc:
            out += [to_mdx(doc)]
        rows = []
        for item in node.body:
            if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name) and not item.target.id.startswith("_"):
                rows.append((f"`{item.target.id}`", f"`{ast.unparse(item.annotation)}`"))
            elif isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
                summary = _summary(ast.get_docstring(item))
                if _is_property(item):
                    rows.append((f"`{item.name}`", _cell(summary)))
                else:
                    signature = _signature(item.name, item, drop_self=True).replace("\n", " ").replace("( ", "(").replace(", )", ")")
                    signature = re.sub(r"\s+", " ", signature)
                    rows.append((f"`{signature}`", _cell(summary)))
        if rows:
            out += ["| Member | What it is |", "|---|---|", *(f"| {a.replace('|', chr(92) + '|')} | {b} |" for a, b in rows), ""]
    else:
        out += ["```python", _signature(f"nb.{name}", node), "```", ""]
        if doc:
            out += [to_mdx(doc)]
    if used:
        out += ["**Used in:** " + ", ".join(f"`{label}`" for label in used), ""]
    return "\n".join(out)


def _cell(text: str) -> str:
    """Prose for a table cell: escaped like any prose, and a pipe cannot end the cell."""
    return _prose(text).replace("|", "\\|")


def _kit_commands() -> str:
    """Every `exakit` command, grouped as the kit's own help groups them, from setup/help/exakit.json: what
    `exakit help` prints. A command the help adds appears here the next time this runs."""
    doc = json.loads(KIT_HELP.read_text(encoding="utf-8"))
    by_name = {entry["command"]: entry for entry in doc.get("commands", [])}
    out = ["---", 'title: "All exakit commands"',
           f'description: "Every command of the kit, {len(by_name)} in all, with what it takes and what it does."',
           "---", "", GENERATED.replace("the docstrings in notebook/package/exakit_nb", "setup/help/exakit.json"), "",
           "`exakit help <command>` prints a command's full reference on this computer, and `exakit catalog <word>`",
           "searches them.", ""]
    listed: set[str] = set()
    groups = [(group.get("title", ""), group.get("commands", [])) for group in doc.get("groups", [])]
    rest = [name for name in by_name if name not in {n for _, names in groups for n in names}]
    for title, names in groups + ([("Other", rest)] if rest else []):
        rows = [by_name[name] for name in names if name in by_name and name not in listed]
        if not rows:
            continue
        out += [f"## {_prose(title)}", "", "| Command | Takes | What it does |", "|---|---|---|"]
        for entry in rows:
            listed.add(entry["command"])
            takes = " ".join(str(entry.get("options") or "").split())
            takes_cell = "`" + takes.replace("|", "\\|").replace("`", "'") + "`" if takes else ""
            out.append(f"| `exakit {entry['command']}` | {takes_cell} | {_cell(str(entry.get('summary') or ''))} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def build() -> dict[Path, str]:
    """Every generated file, as path -> text."""
    names = exported()
    usage = _usage()
    by_module: dict[str, list[tuple[str, str]]] = {}
    for name, module, original in names:
        by_module.setdefault(module, []).append((name, original))
    known = [(stem, slug, title) for stem, slug, title in PAGES if stem in by_module]
    extra = sorted(set(by_module) - {stem for stem, _, _ in PAGES})
    pages = known + [(stem, stem.replace("_", "-"), stem.replace("_", " ").capitalize()) for stem in extra]

    files: dict[Path, str] = {}
    commands: dict[str, str] = {}
    index_rows: list[tuple[str, str, str]] = []
    for stem, slug, title in pages:
        tree = _tree(stem)
        module_doc = ast.get_docstring(tree) or ""
        description = _plain(_summary(module_doc)) or title
        body = [f"---\ntitle: {json.dumps(title)}\ndescription: {json.dumps(description)}\n---", "", GENERATED, ""]
        paragraphs = module_doc.strip().split("\n\n")
        if paragraphs and " ".join(line.strip() for line in paragraphs[0].split("\n")) == re.sub(r"`([^`]+)`", r"``\1``", _summary(module_doc)):
            paragraphs = paragraphs[1:]                  # the page's description already says it
        rest = "\n\n".join(paragraphs).strip("\n")
        if rest.strip():
            body += [to_mdx(rest), ""]
        for name, original in by_module[stem]:
            node = _definition(tree, original)
            if node is None:
                raise SystemExit(f"nb_docs: {stem}.py has no top-level definition named {original} (exported as nb.{name})")
            body += [_entry(name, node, usage.get(name, [])), ""]
            commands[name] = f"/{SECTION}/development/reference/{slug}#{name}"
            index_rows.append((name, slug, _summary(ast.get_docstring(node))))
        files[REFERENCE / f"{slug}.mdx"] = "\n".join(body).rstrip() + "\n"

    table = ["| Command | What it does |", "|---|---|"]
    for name, slug, summary in sorted(index_rows, key=lambda row: (row[0].lower(), row[0])):
        table.append(f"| [`nb.{name}`](/{SECTION}/development/reference/{slug}#{name}) | {_cell(summary)} |")
    files[REFERENCE / "index.mdx"] = "\n".join([
        "---", 'title: "All commands"',
        f'description: "Every public helper of exakit.nb, {len(index_rows)} in all, with the page that documents it."',
        "---", "", GENERATED, "",
        "Every notebook starts with `import exakit.nb as nb`. Each name below is one call a cell can make, and the same",
        "call a guided card makes behind its buttons.", "",
        "```python", "import exakit.nb as nb", "nb.docs(nb.describe)     # open one command's page from a notebook", "```", "",
        *table, "",
    ])
    files[REFERENCE / "meta.json"] = json.dumps(
        {"title": "Notebook commands", "pages": ["index", *(slug for _, slug, _ in pages)]}, indent=2) + "\n"
    files[KIT_COMMANDS] = _kit_commands()
    files[COMMANDS] = json.dumps(dict(sorted(commands.items(), key=lambda item: (item[0].lower(), item[0]))), indent=2) + "\n"
    return files


# ---------------------------------------------------------------------------------------------------------------------
# the shipped site
# ---------------------------------------------------------------------------------------------------------------------

_NOT_SOURCE = {"node_modules", ".next", "out", "site", ".source", "next-env.d.ts", ".DS_Store"}


def sources_digest() -> str:
    """One digest of everything the site is built from (pages, components, styles, the locked dependencies)."""
    digest = hashlib.sha256()
    for path in _sources():
        digest.update(path.relative_to(DOCS).as_posix().encode() + b"\0" + path.read_bytes() + b"\0")
    return digest.hexdigest()


def _sources() -> list[Path]:
    return [path for path in sorted(DOCS.rglob("*"))
            if path.is_file() and not (_NOT_SOURCE & set(path.relative_to(DOCS).parts)) and path.suffix != ".tsbuildinfo"]


def publish() -> int:
    out = DOCS / "out"
    if not (out / "index.html").is_file():
        print("nb_docs: notebook/docs/out has no built site. Run `npm ci && npm run build` in notebook/docs first.", file=sys.stderr)
        return 1
    # The stamp says which sources the site was built from, so the build must be newer than every one of them:
    # publishing an older build would stamp it with pages it does not hold.
    built = (out / "index.html").stat().st_mtime
    newer = [path.relative_to(DOCS).as_posix() for path in _sources() if path.stat().st_mtime > built]
    if newer:
        print(f"nb_docs: notebook/docs/out is older than {len(newer)} of its sources (for example {newer[0]}). "
              "Run `npm run build` in notebook/docs, then publish again.", file=sys.stderr)
        return 1
    if not (out / "commands.json").is_file():
        print("nb_docs: the build has no commands.json. Run `python3 tools/nb_docs.py` and build again.", file=sys.stderr)
        return 1
    if SITE.exists():
        shutil.rmtree(SITE)
    shutil.copytree(out, SITE, ignore=shutil.ignore_patterns(".DS_Store"))
    (SITE / STAMP).write_text(json.dumps({"sources": sources_digest()}, indent=2) + "\n", encoding="utf-8")
    files = [path for path in SITE.rglob("*") if path.is_file()]
    size = sum(path.stat().st_size for path in files)
    print(f"published {len(files)} files, {size / 1e6:.1f} MB, to {SITE.relative_to(ROOT)}")
    return 0


def check(files: dict[Path, str]) -> int:
    problems = []
    for path, text in files.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            problems.append(f"stale: {path.relative_to(ROOT)}")
    expected = {path for path in files if path.parent == REFERENCE}
    for path in sorted(REFERENCE.glob("*")) if REFERENCE.is_dir() else []:
        if path not in expected:
            problems.append(f"not generated any more: {path.relative_to(ROOT)}")
    stamp = SITE / STAMP
    if not stamp.is_file():
        problems.append("notebook/docs/site is missing: build the site and run `python3 tools/nb_docs.py --publish`")
    elif not problems and json.loads(stamp.read_text(encoding="utf-8")).get("sources") != sources_digest():
        problems.append("notebook/docs/site was built from older sources: `npm run build` in notebook/docs, then "
                        "`python3 tools/nb_docs.py --publish`")
    for problem in problems:
        print(f"nb_docs: {problem}", file=sys.stderr)
    if problems and any(problem.startswith(("stale", "not generated")) for problem in problems):
        print("nb_docs: run `python3 tools/nb_docs.py`, rebuild the site, then `--publish`", file=sys.stderr)
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated page or the shipped site is stale")
    parser.add_argument("--publish", action="store_true", help="copy the built out/ to site/ and stamp it")
    args = parser.parse_args()
    if args.publish:
        return publish()
    files = build()
    if args.check:
        return check(files)
    REFERENCE.mkdir(parents=True, exist_ok=True)
    expected = {path for path in files if path.parent == REFERENCE}
    for path in REFERENCE.glob("*"):
        if path not in expected:
            path.unlink()
    changed = 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed += 1
    print(f"{len(files)} generated files, {changed} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
