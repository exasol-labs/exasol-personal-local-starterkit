#!/usr/bin/env python3
"""The notebooks' documentation site (notebook/docs): its generated pages, and the built site the kit ships.

    python3 tools/nb_docs.py             # write the command reference from the code (content/docs/reference)
    python3 tools/nb_docs.py --check     # exit 1 when a generated page or the shipped site is stale; writes nothing
    python3 tools/nb_docs.py --publish   # after `npm run build` in notebook/docs: copy out/ to site/, stamp it

The reference is read from the source, not typed: every name in ``exakit.nb``'s ``__all__`` with its signature and
docstring, one page per module (in the persona section named by SECTION), plus ``public/commands.json`` (name -> page and anchor), which ``nb.docs(nb.describe)``
reads to open a command's page. Only ``ast`` is used, so this runs on any Python 3.9+ with nothing installed.

The site itself is built with Node on a maintainer's machine (``npm ci && npm run build`` in notebook/docs) and
shipped as plain files in notebook/docs/site; the kit serves them with its own Python (exakit_nb/docs.py), so a user
never needs Node. ``site/BUILD.json`` holds a digest of the sources the site was built from: --check fails when they
have changed since, so an edited page cannot ship with an old site.
"""

