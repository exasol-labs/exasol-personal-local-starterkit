class SqlError(Exception):
    pass


class Outcome(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


def emit(level, text):
    print("%s %s" % (level, text))
    sys.stdout.flush()


def load_package_manifest():
    with open(os.path.join(HERE, "manifest.json"), encoding="utf-8") as handle:
        return json.load(handle)


def normalize_slot(value):
    """'"PREPROC_RT"."MASTER"' and 'preproc_rt.master' are the same script."""
    if value is None:
        return ""
    return str(value).replace('"', "").strip().upper()


def sql_literal(value):
    return "'" + str(value).replace("'", "''") + "'"


PYTHON_SCRIPT = re.compile(r"(?i)^\s*CREATE\s+(OR\s+REPLACE\s+)?PYTHON3\b[^(]*?SCRIPT\s+([\w.\"]+)")


def core_only(text):
    """release.sql without its PYTHON3 script blocks: (text, [removed names]).

    A script block runs from its "--/" opener (and the comment header under
    it) to the lone "/" that ends the body. Everything else - every Lua
    script, table, grant and seed - is kept byte for byte.
    """
    lines = text.splitlines(True)
    kept, removed, index = [], [], 0
    while index < len(lines):
        if lines[index].strip() == "--/":
            ahead = index + 1
            while ahead < len(lines) and (not lines[ahead].strip() or lines[ahead].lstrip().startswith("--")):
                ahead += 1
            match = PYTHON_SCRIPT.match(lines[ahead]) if ahead < len(lines) else None
            if match:
                end = ahead + 1
                while end < len(lines) and lines[end].strip() != "/":
                    end += 1
                removed.append(match.group(2).replace('"', "").upper())
                index = end + 1
                continue
        kept.append(lines[index])
        index += 1
    return "".join(kept), removed


def sha256_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_of(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 16), b""):
            digest.update(block)
    return digest.hexdigest()


class Exapump(object):
    """One exapump invocation is one connection; that is the session boundary."""

    def __init__(self, binary, profile, log_path):
        self.binary = binary
        self.profile = profile
        self.log_path = log_path

    def _log(self, text):
        if not self.log_path or not text:
            return
        try:
            with open(self.log_path, "a", encoding="utf-8") as handle:
                for line in text.splitlines():
                    handle.write("PREPROC %s\n" % line)
        except OSError:
            pass

    def run(self, sql, timeout=QUERY_TIMEOUT):
        """Run SQL text on one connection; return the result arrays of its SELECTs."""
        command = [self.binary, "sql", "-p", self.profile, "-f", "json"]
        # LF only. exapump ends a script body at a "/" followed by a bare LF
        # (src/commands/sql.rs, scan_script_body), so a "/" line ending in CRLF
        # is body text: the first script then swallowed every statement after it
        # and exapump still exited 0. An artifact generated on Windows is written
        # in text mode, CRLF, and that is how JSON Tables printed "registered"
        # with nothing but its REFUSE script in the database.
        sql = sql.replace("\r\n", "\n")
        try:
            done = subprocess.run(command, input=sql.encode("utf-8"), stdout=subprocess.PIPE,
                                  stderr=subprocess.PIPE, timeout=timeout)
        except subprocess.TimeoutExpired:
            raise SqlError("exapump did not answer within %ss" % timeout)
        except OSError as error:
            raise SqlError("could not run exapump (%s): %s" % (self.binary, error))
        out = done.stdout.decode("utf-8", "replace")
        err = done.stderr.decode("utf-8", "replace")
        self._log(err)
        if done.returncode != 0:
            raise SqlError(self._reason(err) or "exapump exited with %s" % done.returncode)
        return self._results(out)

    @staticmethod
    def _results(text):
        decoder = json.JSONDecoder()
        results, index = [], 0
        while True:
            while index < len(text) and text[index].isspace():
                index += 1
            if index >= len(text):
                return results
            try:
                value, index = decoder.raw_decode(text, index)
            except ValueError:
                raise SqlError("exapump printed something that is not JSON: %r" % text[index:index + 80])
            results.append(value if isinstance(value, list) else [])

    @staticmethod
    def _reason(err):
        """The database's own message, without the session id."""
        for line in reversed(err.splitlines()):
            line = line.strip()
            if line.startswith("Error:") or "execution failed" in line:
                line = re.sub(r"^Error:\s*", "", line)
                line = re.sub(r"^Query execution failed:\s*(Protocol error:\s*)?", "", line)
                return re.sub(r"\s*\(Session: \d+\)", "", line)
        return ""


class Preprocessor(object):
    def __init__(self, args):
        self.args = args
        self.db = Exapump(args.exapump, args.profile, getattr(args, "log", None))
        self.package = load_package_manifest()
        self.dispatcher = self.package["dispatcher"]

    # --- state -----------------------------------------------------------------
    def record(self):
        try:
            return state.component(state.read_manifest(self.args.manifest), COMPONENT)
        except state.StateError:
            return {}

    def save(self, fields, remove=()):
        state.update_component(self.args.manifest, COMPONENT, fields, remove)

    def inspect(self):
        """What the database holds right now."""
        # BYPASS: a framework that breaks every statement must still be
        # inspectable, so ensure reaches its verify and rolls the slot back.
        results = self.db.run("\n".join([
            BYPASS,
            "SELECT SYSTEM_VALUE AS S FROM EXA_PARAMETERS WHERE PARAMETER_NAME = 'SQL_PREPROCESSOR_SCRIPT';",
            "SELECT SCHEMA_NAME AS N FROM EXA_SCHEMAS WHERE SCHEMA_NAME IN (%s);"
            % ", ".join(sql_literal(name) for name in self.package["schemas"]),
            "SELECT SCRIPT_SCHEMA || '.' || SCRIPT_NAME AS N FROM EXA_ALL_SCRIPTS"
            " WHERE SCRIPT_SCHEMA IN (%s);" % ", ".join(sql_literal(name) for name in self.package["schemas"]),
            "SELECT ROLE_NAME AS N FROM EXA_DBA_ROLES WHERE ROLE_NAME = %s;" % sql_literal(self.package["role"]),
        ]))
        # The last four: whether exapump prints a result for the ALTER SESSION
        # in front is the tool's business.
        if len(results) not in (4, 5):
            raise SqlError("the inspection returned %d result sets, expected 4" % len(results))
        slot_rows, schema_rows, script_rows, role_rows = results[-4:]
        scripts = set(row.get("N") for row in script_rows)
        schemas = set(row.get("N") for row in schema_rows)
        return {
            "slot": normalize_slot(slot_rows[0].get("S")) if slot_rows else "",
            "schemas": sorted(schemas),
            "scripts": sorted(scripts),
            "role": bool(role_rows),
            "present": bool(scripts or schemas or role_rows),
            "missing": [name for name in self.package["required_scripts"] if name not in scripts]
                       + [name for name in self.package["schemas"] if name not in schemas]
                       + ([] if role_rows else [self.package["role"]]),
        }

    # --- checks ----------------------------------------------------------------
    def ordinary_sql_works(self):
        rows = self.db.run(ORDINARY)
        return bool(rows and rows[0] and rows[0][0].get("R") == "EXAKIT_PP_ORDINARY")

    def probe_dispatches(self, sql_prefix=""):
        rows = self.db.run(sql_prefix + PROBE_IN)
        last = rows[-1] if rows else []
        return bool(last and last[0].get("R") == PROBE_OUT)

    def deploy_probe(self):
        with open(os.path.join(HERE, "checks", "probe_module.sql"), encoding="utf-8") as handle:
            module = handle.read()
        self.drop_probe(quiet=True)
        self.db.run("\n".join([
            BYPASS, module,
            "EXECUTE SCRIPT PREPROC.RULE_ENSURE('USER', %s, 'EXPAND', %s, %s, NULL, FALSE);"
            % (sql_literal(self.args.admin_user.upper()), sql_literal(PROBE_SCRIPT), sql_literal(PROBE_FUNCTION)),
        ]))

    def drop_probe(self, quiet=False):
        """Remove every probe rule and the probe script. Safe to repeat."""
        try:
            results = self.db.run(BYPASS + "\nSELECT RULE_ID AS ID FROM PREPROC.CONFIG WHERE SCRIPT_NAME = %s;"
                                  % sql_literal(PROBE_SCRIPT))
            ids = [row.get("ID") for row in (results[-1] if results else []) if row.get("ID") is not None]
            statements = [BYPASS]
            statements += ["EXECUTE SCRIPT PREPROC.RULE_DROP(%s, FALSE);" % int(rule_id) for rule_id in ids]
            statements.append("DROP SCRIPT IF EXISTS %s;" % PROBE_SCRIPT)
            self.db.run("\n".join(statements))
        except SqlError as error:
            if not quiet:
                emit("WARN", "The activation probe could not be removed (%s); it is scoped to %s only."
                     % (error, self.args.admin_user.upper()))

    def restore_slot(self, previous):
        """Put the database default back to what it was before this run."""
        value = previous if previous else "NULL"
        self.db.run("%s\nALTER SYSTEM SET sql_preprocessor_script = %s;" % (BYPASS, value))

    # --- the flows -------------------------------------------------------------
    def fresh_install(self, recover=False):
        package = self.args.package
        if not package or not os.path.isfile(package):
            raise Outcome(EXIT_NEED_PACKAGE, "Fresh install: fetching the pinned framework package")
        actual = sha256_of(package)
        if actual != self.args.pin_sha256.lower():
            raise Outcome(EXIT_BAD_PACKAGE, "the framework package does not match the pinned SHA-256"
                          " (expected %s, got %s)" % (self.args.pin_sha256.lower(), actual))
        with open(package, encoding="utf-8", newline="") as handle:
            body, removed = core_only(handle.read())
        core_sha = sha256_text(body)
        if self.args.pin_core_sha256 and core_sha != self.args.pin_core_sha256.lower():
            raise Outcome(EXIT_BAD_PACKAGE, "the core-only package derived from the verified download does not"
                          " match its pin (expected %s, got %s)" % (self.args.pin_core_sha256.lower(), core_sha))
        if recover:
            self.drop_own_partial_install()
        # Recorded BEFORE any SQL runs: a run that dies part way leaves this
        # record, and it is the only proof the next run has that the objects it
        # finds are the kit's own and safe to drop.
        self.save({"state": "installing", "version": self.args.pin_version, "source_ref": self.args.pin_ref,
                   "sha256": actual, "package": "core-only", "core_sha256": core_sha,
                   "left_out": removed, "validated": False},
                  remove=("installed_at", "verified_at", "activated_at", "previous_setting", "origin"))
        try:
            self.db.run(BYPASS + "\n" + body, timeout=INSTALL_TIMEOUT)
        except SqlError as error:
            raise Outcome(EXIT_FAILED, "the framework install did not finish: %s" % error)
        found = self.inspect()
        if found["missing"]:
            raise Outcome(EXIT_FAILED, "the framework install finished without %s" % ", ".join(found["missing"]))
        self.save({"state": "installed", "origin": "kit", "installed_at": now()})
        emit("INFO", "SQL preprocessor framework %s installed (not active yet)" % self.args.pin_version)
        return found

    def drop_own_partial_install(self):
        """Drop what the kit's own interrupted install created, and nothing else."""
        seeds = set(self.package["seed_scripts"]) | {PROBE_SCRIPT}
        # Only a CONFIG table that does not exist yet means nothing anyone
        # configured; one that cannot be read refuses (audit SCR-06): a failed
        # read never reads as "no rules" before DROP SCHEMA ... CASCADE.
        try:
            results = self.db.run(BYPASS + "\nSELECT TABLE_NAME AS N FROM EXA_DBA_TABLES"
                                  " WHERE TABLE_SCHEMA = 'PREPROC' AND TABLE_NAME = 'CONFIG';")
            foreign = []
            if not results or results[-1]:
                results = self.db.run(BYPASS + "\nSELECT DISTINCT SCRIPT_NAME AS N FROM PREPROC.CONFIG;")
                foreign = sorted(row.get("N") for row in results[-1] if row.get("N") not in seeds)
        except (SqlError, IndexError) as error:
            raise Outcome(EXIT_FAILED, "an interrupted framework install was found, but whether PREPROC.CONFIG"
                          " holds anyone's rules could not be read (%s); nothing was dropped. Check exakit status"
                          " and retry the command below" % (str(error) or "no answer"))
        if foreign:
            raise Outcome(EXIT_FAILED, "an interrupted framework install was found, but PREPROC.CONFIG"
                          " already has rules for %s; the kit will not drop it. Keep them by activating the framework"
                          " (ALTER SYSTEM SET sql_preprocessor_script = PREPROC_RT.MASTER), or remove those rules,"
                          " then run the command below" % ", ".join(foreign))
        statements = [BYPASS]
        statements += ["DROP SCHEMA IF EXISTS %s CASCADE;" % name for name in self.package["schemas"]]
        statements.append("DROP ROLE IF EXISTS %s CASCADE;" % self.package["role"])
        try:
            self.db.run("\n".join(statements))
        except SqlError as error:
            raise Outcome(EXIT_FAILED, "the interrupted framework install could not be cleaned up: %s" % error)
        emit("INFO", "Cleaned up an interrupted framework install before reinstalling")

    def activate(self, previous):
        """Trial in one session, then the database default, then fresh-connection checks."""
        try:
            try:
                self.deploy_probe()
            except SqlError as error:
                raise Outcome(EXIT_FAILED, "the activation probe could not be deployed: %s" % error)
            trial = "ALTER SESSION SET sql_preprocessor_script = %s;\n%s;\n" % (self.dispatcher, ORDINARY)
            try:
                rows = self.db.run(trial + PROBE_IN)
            except SqlError as error:
                raise Outcome(EXIT_FAILED, "a session using the dispatcher failed: %s" % error)
            ordinary_ok = len(rows) >= 2 and rows[0] and rows[0][0].get("R") == "EXAKIT_PP_ORDINARY"
            probe_ok = bool(rows and rows[-1] and rows[-1][0].get("R") == PROBE_OUT)
            if not ordinary_ok:
                raise Outcome(EXIT_FAILED, "ordinary SQL did not come back unchanged in a session using the dispatcher")
            if not probe_ok:
                raise Outcome(EXIT_FAILED, "the dispatcher did not run a module scoped to %s"
                              % self.args.admin_user.upper())
            # The recovery value goes on disk before the default changes.
            self.save({"previous_setting": previous})
            try:
                self.db.run("%s\nALTER SYSTEM SET sql_preprocessor_script = %s;" % (BYPASS, self.dispatcher))
            except SqlError as error:
                raise Outcome(EXIT_FAILED, "the database default could not be set: %s" % error)
            problem = self.verify_active(dispatch=True)
            if problem:
                self.roll_back(previous, problem)
        finally:
            self.drop_probe()
        self.save({"state": "active", "validated": True, "activated_at": now(), "verified_at": now()})

    def verify_active(self, dispatch=False):
        """None when fresh connections see a working dispatcher, else the reason."""
        try:
            if not self.ordinary_sql_works():
                return "ordinary SQL did not come back unchanged with the framework active"
            if dispatch and not self.probe_dispatches():
                return "a fresh connection did not dispatch to the scoped probe module"
            results = self.db.run("\n".join([
                "SELECT SYSTEM_VALUE AS S FROM EXA_PARAMETERS WHERE PARAMETER_NAME = 'SQL_PREPROCESSOR_SCRIPT';",
                "SELECT COUNT(*) AS N FROM PREPROC_RT.MY_PIPELINE;",
            ]))
        except SqlError as error:
            return "a fresh connection failed with the framework active: %s" % error
        slot = normalize_slot(results[0][0].get("S")) if results and results[0] else ""
        if slot != self.dispatcher:
            return "the database default is %s, not %s" % (slot or "empty", self.dispatcher)
        return None

    def roll_back(self, previous, problem):
        try:
            self.restore_slot(previous)
            restored = self.ordinary_sql_works()
        except SqlError as error:
            raise Outcome(EXIT_FAILED, "%s, and restoring the previous setting failed: %s" % (problem, error))
        self.save({"state": "installed", "validated": False}, remove=("activated_at", "verified_at"))
        if not restored:
            raise Outcome(EXIT_FAILED, "%s; the previous setting was restored but ordinary SQL still fails" % problem)
        raise Outcome(EXIT_FAILED, "%s; the previous setting was restored and ordinary SQL works" % problem)

    def upgrade_note(self, rec):
        installed = rec.get("version")
        if not installed or installed == self.args.pin_version:
            return
        tested = [step for step in self.package.get("upgrades") or []
                  if step.get("from") == installed and step.get("to") == self.args.pin_version]
        if not tested:
            emit("WARN", "Framework %s is installed and this kit pins %s; there is no tested upgrade path"
                 " yet, so the installed framework is kept as it is" % (installed, self.args.pin_version))

    def ensure(self):
        try:
            found = self.inspect()
        except SqlError as error:
            raise Outcome(EXIT_FAILED, "the database could not be inspected: %s" % error)
        rec = self.record()
        ours = rec.get("state") in ("installing", "installed", "active")
        slot = found["slot"]

        if slot and slot != self.dispatcher:
            return self.decline(slot)
        if rec.get("declined"):
            # The slot is free again: whoever held it let go, so the decline
            # recorded for it no longer stands and the framework is set up.
            self.save({}, remove=DECLINE_FIELDS)
            rec = self.record()

        if not found["present"]:
            # A slot naming a dispatcher that no longer exists is no setting
            # worth restoring.
            self.fresh_install()
            self.activate(previous="")
        elif not ours and slot != self.dispatcher:
            raise Outcome(EXIT_CONFLICT, "a preprocessor framework the kit did not install is already in this"
                          " database and is not active; it was left unchanged. To have the kit manage it, activate it"
                          " (ALTER SYSTEM SET sql_preprocessor_script = PREPROC_RT.MASTER) and run the command below -"
                          " the kit then verifies and adopts it")
        elif rec.get("state") == "installing" and slot != self.dispatcher:
            self.fresh_install(recover=True)
            self.activate(previous="")
        else:
            if found["missing"]:
                raise Outcome(EXIT_FAILED, "framework objects are missing (%s); the kit does not replay its"
                              " fresh install over an existing framework" % ", ".join(found["missing"]))
            if not ours:
                # Installed and activated by hand: verified, then managed.
                self.save({"state": "active", "origin": "pre-existing", "validated": False})
                rec = self.record()
            self.upgrade_note(rec)
            if slot != self.dispatcher:
                if rec.get("state") == "active":
                    emit("INFO", "The framework was installed but is no longer active - activating it again")
                # The slot is empty here (any other value was a conflict above),
                # so the setting to restore is the one recorded before the kit
                # first activated, or empty.
                self.activate(previous=rec.get("previous_setting", ""))
            else:
                problem = self.verify_active()
                if problem:
                    self.roll_back(rec.get("previous_setting", ""), problem)
                # "active" here too: a framework activated by hand after an
                # interrupted install was still recorded as "installing".
                self.save({"state": "active", "validated": True, "verified_at": now()})
                emit("OK", "SQL preprocessor framework %s verified and active" % self.version_label())
                self.refresh_if_stale()
                return EXIT_OK
        emit("OK", "SQL preprocessor framework %s installed, tested and activated" % self.version_label())
        emit("OK", "Ordinary SQL verified with the framework active")
        return EXIT_OK

    def decline(self, slot):
        """The slot holds a script the kit does not manage: the user's own
        preprocessor. That is a choice, not a fault. The slot is left exactly as
        it is, the choice is recorded with its holder, and the task is done as
        declined, so no installer pass and no `exakit update` keeps retrying
        (and failing) on it. The way to opt in later is said in full the first
        time the holder is seen; every pass after that says one line."""
        rec = self.record()
        first = not (rec.get("declined") and rec.get("slot_holder") == slot)
        self.save({"declined": True, "slot_holder": slot,
                   "declined_at": now() if first else rec.get("declined_at") or now()})
        if first:
            rerun = getattr(self.args, "opt_in_command", "") or "the kit's installer"
            emit("INFO", "The database's SQL preprocessor slot holds %s, a script the kit does not manage, so it"
                 " keeps the slot and the kit's preprocessor framework stays off. To use the framework later, clear"
                 " the slot (ALTER SYSTEM SET sql_preprocessor_script = NULL) or move that script into a framework"
                 " module, then run %s again" % (slot, rerun))
        emit("OK", "SQL preprocessor slot left to %s; the kit's framework is not active" % slot)
        return EXIT_DECLINED

    def refresh_if_stale(self):
        """Rules reach users through PREPROC.RESOLUTION, a per-user table the
        framework rebuilds only on REFRESH (and on its own admin scripts). A user
        or role grant created since then gets none of its ROLE-scoped rules, and
        the framework expects its operator to refresh - here, every kit run
        (the installer, and every `exakit update`). Stale is STATUS's verdict,
        or a user that a ROLE PUBLIC rule reaches and RESOLUTION has no row
        for: a database user created since the last refresh gets none of the
        kit's modules until one runs. Never fatal: the framework works, it is
        only behind."""
        try:
            rows = self.db.run("\n".join([BYPASS, "EXECUTE SCRIPT PREPROC.STATUS;", UNRESOLVED_USERS]))
            if len(rows) < 2:
                raise SqlError("the refresh check returned %d result sets, expected 2" % len(rows))
            row = rows[-2][0] if rows[-2] else {}
            unresolved = int((rows[-1][0] if rows[-1] else {}).get("N") or 0)
            if str(row.get("IS_STALE")).lower() != "true" and not unresolved:
                return
            self.db.run(BYPASS + "\nEXECUTE SCRIPT PREPROC.REFRESH;")
        except SqlError as error:
            emit("WARN", "The framework's rule resolution could not be refreshed (%s); as the admin, run:"
                 " EXECUTE SCRIPT PREPROC.REFRESH" % error)
            return
        last = str(row.get("LAST_REFRESH") or "")[:16]
        emit("OK", "Rule resolution refreshed for users and roles changed since %s"
             % ("the last refresh (%s, database time)" % last if last else "the install"))

    def version_label(self):
        return self.record().get("version") or "(installed outside the kit)"


# --- add-on modules -------------------------------------------------------------------------------------------
#
# The framework's own module contract (docs/module-authoring.md at the pinned
# release): an entry function fn(text) -> nil|string in a versioned Lua script,
# a rule, and a module.toml. The kit adds a [kit] table to module.toml:
#
#   addon      the add-on id (the folder name)
#   label      how the add-on is named in messages
#   receipt    the manifest key of the add-on's receipt (installed = kit-owned,
#              a version, not mid-install)
#   artifact   the pinned artifact, a file in the folder whose SHA-256 is
#              module.toml's sha256; or
#   generated  true: the add-on builds the artifact for this database and hands
#              it over (--artifact). Its object names carry the {VERSION} token,
#              which the kit replaces with the version it deploys.
#   generator  optional, generated only: the command (a list; {python},
#              {kit_root}, {home}, {exapump}, {profile} and {out} are filled
#              in) that writes the artifact to {out}, for the framework's own
#              registration pass.
#
# The rule's scope is module.toml's suggested_scope. The kit's modules use
# ROLE PUBLIC: the framework resolves PUBLIC to every user in the database
# (a synthetic PUBLIC edge per user, refreshed on every REFRESH), so the module
# reaches the administrator, the MCP read-only login, Dash Server and, after the
# next refresh (refresh_if_stale, every installer run and `exakit update`), any
# user created later - the database-wide reach an add-on's own ALTER SYSTEM had,
# without taking the slot.

MODULES_DIR = os.path.join(HERE, "modules")
VERSION_TOKEN = "{VERSION}"
PHASES = ("TRANSLATE", "EXPAND", "REWRITE")
IDENTIFIER = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
CREATE_SCRIPT = re.compile(
    r"(?is)^\s*CREATE\s+(?:OR\s+REPLACE\s+)?((?:[A-Z_][A-Z0-9_]*\s+)?(?:(?:SCALAR|SET)\s+)?SCRIPT)\s+([\w.{}\"]+)")
MODULE_TIMEOUT = 300
NOTE_MAX = 64          # PREPROC.MODULES.library_version is VARCHAR(64)


class ModuleError(Exception):
    pass


def split_artifact(text):
    """The statements of an artifact: a --/ ... / block is one, anything else ends at ';'."""
    statements, current, block = [], [], False
    for line in text.splitlines():
        stripped = line.strip()
        if block:
            if stripped == "/":
                statements.append("\n".join(current).strip())
                current, block = [], False
            else:
                current.append(line)
            continue
        if stripped == "--/" and not current:
            block = True
            continue
        if not current and (not stripped or stripped.startswith("--")):
            continue
        current.append(line)
        if stripped.endswith(";"):
            statements.append("\n".join(current).strip()[:-1].strip())
            current = []
    if block:
        raise ModuleError("a --/ block is not closed by a line holding only /")
    if "\n".join(current).strip():
        raise ModuleError("the last statement does not end with ;")
    return statements


def artifact_objects(text):
    """[(type, name)] the artifact creates, in file order. Scripts only: the kit's
    modules are Lua, and an artifact holds nothing but the objects it creates."""
    objects = []
    for statement in split_artifact(text):
        match = CREATE_SCRIPT.match(statement)
        if not match:
            raise ModuleError("the artifact holds a statement that creates no script: %s"
                              % statement.splitlines()[0][:80])
        kind = " ".join(match.group(1).upper().split())
        objects.append((kind if kind != "SCRIPT" else "LUA SCRIPT", match.group(2).replace('"', "").upper()))
    if not objects:
        raise ModuleError("the artifact creates nothing")
    return objects


def version_tuple(text):
    return tuple(int(part) for part in re.findall(r"\d+", str(text or ""))[:3]) or (0,)


def load_module(addon, modules_dir=MODULES_DIR, artifact=None):
    """module.toml of an add-on, checked against the framework's contract, with its
    artifact (verified) when one is given or pinned. None when there is no folder."""
    folder = os.path.join(modules_dir, addon)
    path = os.path.join(folder, "module.toml")
    if not re.match(r"^[a-z][a-z0-9-]*$", addon or "") or not os.path.isfile(path):
        return None
    try:
        import tomllib
    except ImportError:
        raise ModuleError("reading module.toml needs Python 3.11 or newer")
    try:
        with open(path, "rb") as handle:
            doc = tomllib.load(handle)
    except (OSError, ValueError) as error:
        raise ModuleError("%s cannot be read: %s" % (path, error))
    kit = doc.get("kit") if isinstance(doc.get("kit"), dict) else {}
    scope = doc.get("suggested_scope") if isinstance(doc.get("suggested_scope"), dict) else {}
    generated = kit.get("generated") is True
    module = {
        "addon": addon, "folder": folder, "name": str(doc.get("name") or ""),
        "label": str(kit.get("label") or addon), "receipt": str(kit.get("receipt") or ""),
        "phase": str(doc.get("phase") or "").upper(), "script": str(doc.get("script_name") or "").upper(),
        "function": str(doc.get("function") or ""), "deploy_mode": str(doc.get("deploy_mode") or ""),
        "min_framework": str(doc.get("min_framework") or ""), "generated": generated,
        "generator": kit.get("generator") if isinstance(kit.get("generator"), list) else None,
        "scope_type": str(scope.get("type") or "").upper(), "scope_value": str(scope.get("value") or "").upper(),
        "source_repo": str((doc.get("source") or {}).get("repo") or "") or None,
        "source_ref": str((doc.get("source") or {}).get("ref") or "") or None,
    }
    problems = []
    if not IDENTIFIER.match(module["name"]) or module["name"] != module["name"].lower():
        problems.append("name must be snake_case")
    if module["phase"] not in PHASES:
        problems.append("phase must be one of %s" % ", ".join(PHASES))
    if not IDENTIFIER.match(module["function"]):
        problems.append("function must be a plain Lua identifier")
    if module["scope_type"] not in ("ROLE", "USER") or not IDENTIFIER.match(module["scope_value"]):
        problems.append("suggested_scope must be { type = ROLE|USER, value = <name> }")
    if not module["receipt"].startswith("components."):
        problems.append("[kit] receipt must name the add-on's receipt (components.<key>)")
    suffix = "_V" + VERSION_TOKEN if generated else "_V%s" % doc.get("version")
    if generated:
        module["version"] = None
    elif not isinstance(doc.get("version"), int) or doc.get("version") < 1:
        problems.append("version must be a positive integer")
    else:
        module["version"] = doc["version"]
    if not module["script"].startswith("PREPROC_RT.") or not module["script"].endswith(suffix):
        problems.append("script_name must be PREPROC_RT.<NAME>%s" % suffix)
    if problems:
        raise ModuleError("%s: %s" % (path, "; ".join(problems)))
    module["base"] = module["script"][:-len(suffix)] + "_V"
    # The names of everything one version creates, {VERSION} still in them: a deploy that never registered is
    # dropped by these names (Modules.half_made).
    module["templates"] = [str(item.get("name") or "").upper() for item in doc.get("objects") or []
                           if isinstance(item, dict)] or [module["script"]]

    if artifact is None and not generated:
        artifact = os.path.join(folder, str(kit.get("artifact") or ""))
        if not kit.get("artifact") or not os.path.isfile(artifact):
            raise ModuleError("%s: [kit] artifact names no file in %s" % (path, folder))
    if artifact is None:
        return module
    if not generated and os.path.dirname(os.path.abspath(artifact)) != os.path.abspath(folder):
        raise ModuleError("%s pins its artifact; a generated one is not accepted" % module["label"])
    try:
        with open(artifact, "rb") as handle:
            raw = handle.read()
        text = raw.decode("utf-8")
    except (OSError, UnicodeError) as error:
        raise ModuleError("the artifact %s cannot be read: %s" % (artifact, error))
    digest = hashlib.sha256(raw).hexdigest()
    if not generated and digest != str(doc.get("sha256") or "").lower():
        raise ModuleError("%s does not match the SHA-256 pinned in module.toml (got %s)" % (artifact, digest))
    objects = artifact_objects(text)
    declared = [(" ".join(str(item.get("type") or "").upper().split()), str(item.get("name") or "").upper())
                for item in doc.get("objects") or [] if isinstance(item, dict)]
    if declared and sorted(declared) != sorted(objects):
        raise ModuleError("the artifact creates %s, module.toml declares %s"
                          % (", ".join(n for _, n in objects), ", ".join(n for _, n in declared)))
    if not declared and len(objects) != 1:
        raise ModuleError("an artifact with several objects needs them declared in [[objects]]")
    for kind, name in objects:
        if not name.endswith(suffix):
            raise ModuleError("%s does not carry the module's %s suffix" % (name, suffix))
    if (("LUA SCRIPT", module["script"]) not in objects):
        raise ModuleError("the artifact does not create the entry script %s as a LUA SCRIPT" % module["script"])
    module.update(text=text, sha256=digest, objects=objects)
    return module


def receipt_installed(doc, receipt):
    node = doc
    for key in receipt.split("."):
        node = node.get(key) if isinstance(node, dict) else None
    return isinstance(node, dict) and node.get("ownership") == "kit" and bool(node.get("version")) \
        and node.get("state") != "installing"


def installed_addons(manifest_doc, modules_dir=MODULES_DIR):
    """Add-ons with a module folder whose receipt says the kit installed them."""
    found = []
    for addon in sorted(os.listdir(modules_dir)) if os.path.isdir(modules_dir) else []:
        try:
            module = load_module(addon, modules_dir, artifact=None) if os.path.isfile(
                os.path.join(modules_dir, addon, "module.toml")) else None
        except ModuleError:
            module = {"addon": addon, "receipt": ""}
        if module is None:
            continue
        if not module.get("receipt") or receipt_installed(manifest_doc, module["receipt"]):
            found.append(addon)
    return found


def script_version(name, base):
    if name.startswith(base) and name[len(base):].isdigit():
        return int(name[len(base):])
    return None


def truthy(value):
    return value is True or str(value).lower() in ("true", "1")


class Modules(object):
    """register / retire add-on modules with the framework. Every statement runs
    behind BYPASS, so nothing the kit does here passes through any preprocessor."""

    def __init__(self, args):
        self.args = args
        self.db = Exapump(args.exapump, args.profile, getattr(args, "log", None))
        self.package = load_package_manifest()
        self.modules_dir = getattr(args, "modules_dir", "") or MODULES_DIR

    @contextlib.contextmanager
    def locked(self):
        """One registration at a time on this computer: add-ons install side by side."""
        with state.manifest_lock(self.args.manifest + ".modules"):
            yield

    def framework_record(self):
        try:
            return state.component(state.read_manifest(self.args.manifest), COMPONENT)
        except state.StateError:
            return {}

    def manifest_doc(self):
        try:
            return state.read_manifest(self.args.manifest)
        except state.StateError:
            return {}

    def record_module(self, module, version=None, remove=False):
        modules = dict(self.framework_record().get("modules") or {})
        if remove:
            if module["addon"] not in modules:
                return
            modules.pop(module["addon"], None)
        else:
            entry = {"name": module["name"], "version": version, "sha256": module["sha256"],
                     "script": self.script_for(module, version)}
            held = dict(modules.get(module["addon"]) or {})
            held.pop("registered_at", None)
            if held == entry:
                return
            modules[module["addon"]] = dict(entry, registered_at=now())
        state.update_component(self.args.manifest, COMPONENT, {"modules": modules})

    @staticmethod
    def script_for(module, version):
        return module["base"] + str(version)

    def framework_scripts(self):
        rows = self.db.run(BYPASS + "\nSELECT SCRIPT_SCHEMA || '.' || SCRIPT_NAME AS N FROM EXA_ALL_SCRIPTS"
                           " WHERE SCRIPT_SCHEMA IN ('PREPROC', 'PREPROC_RT');")
        return set(row.get("N") for row in (rows[-1] if rows else []))

    def module_state(self, module):
        """Rules of this module (any version) and its provenance rows."""
        results = self.db.run("\n".join([
            BYPASS,
            "SELECT RULE_ID AS ID, SCOPE_TYPE AS ST, SCOPE_VALUE AS SV, PHASE AS PH, SCRIPT_NAME AS S,"
            " FUNCTION_NAME AS F, ENABLED AS E FROM PREPROC.CONFIG;",
            "SELECT VERSION AS V, STATUS AS ST, SHA256 AS H FROM PREPROC.MODULES WHERE NAME = %s;"
            % sql_literal(module["name"]),
        ]))
        if len(results) < 2:
            raise SqlError("the module state returned %d result sets, expected 2" % len(results))
        rules = [row for row in results[-2] if script_version(str(row.get("S") or "").upper(), module["base"])]
        rows = [{"version": int(row.get("V")), "status": str(row.get("ST") or "").lower(),
                 "sha256": str(row.get("H") or "").lower()} for row in results[-1] if row.get("V") is not None]
        return rules, rows

    def gate(self, module, registering):
        """None when the framework can take modules here, else why not (a skip)."""
        rec = self.framework_record()
        if registering and rec.get("declined"):
            return ("the database's SQL preprocessor slot holds %s, a script the kit does not manage, so %s is not"
                    " registered with the kit's framework" % (rec.get("slot_holder") or "another script",
                                                              module["label"]))
        if registering and rec.get("state") != "active":
            return ("the kit's SQL preprocessor framework is not set up in this database yet; %s registers with it"
                    " when the framework is installed (the installer, or exakit update)" % module["label"])
        if registering and rec.get("version") and module["min_framework"] and \
                version_tuple(rec.get("version")) < version_tuple(module["min_framework"]):
            return "%s needs framework %s or newer; %s is installed" % (module["label"], module["min_framework"],
                                                                       rec.get("version"))
        missing = [name for name in self.package.get("module_scripts") or [] if name not in self.framework_scripts()]
        if missing:
            return ("the SQL preprocessor framework in this database cannot take modules (%s missing), so %s is not"
                    " %s" % (", ".join(missing), module["label"], "registered" if registering else "retired"))
        return None

    def rule_matches(self, rule, module, script):
        return (str(rule.get("S") or "").upper() == script and str(rule.get("F") or "") == module["function"]
                and str(rule.get("PH") or "").upper() == module["phase"]
                and str(rule.get("ST") or "").upper() == module["scope_type"]
                and str(rule.get("SV") or "").upper() == module["scope_value"] and truthy(rule.get("E")))

    def register(self, addon, artifact=None, note=None, quiet=False):
        """Returns (exit code, what happened)."""
        module = load_module(addon, self.modules_dir, artifact)
        if module is None:
            return EXIT_SKIPPED, "%s has no module folder; it needs no SQL preprocessor module" % addon
        if module["generated"] and "text" not in module:
            raise ModuleError("%s builds its module for this database: pass the artifact with --artifact"
                              % module["label"])
        if not receipt_installed(self.manifest_doc(), module["receipt"]):
            return EXIT_SKIPPED, "%s is not installed by the kit; its module is not registered" % module["label"]
        why = self.gate(module, registering=True)
        if why:
            return EXIT_SKIPPED, why
        rules, rows = self.module_state(module)
        scripts = self.framework_scripts()
        mine = [row for row in rows if row["sha256"] == module["sha256"]]
        if module["generated"]:
            if mine:
                version = max(row["version"] for row in mine)
            else:
                seen = [row["version"] for row in rows]
                seen += [script_version(name, module["base"]) or 0 for name in scripts]
                seen += [script_version(str(rule.get("S") or "").upper(), module["base"]) for rule in rules]
                version = max(seen + [0]) + 1
        else:
            version = module["version"]
            clash = [row for row in rows if row["version"] == version and row["status"] == "deployed"
                     and row["sha256"] != module["sha256"]]
            if clash:
                raise ModuleError("%s version %s is deployed with different content; a changed module must ship"
                                  " as a new version" % (module["name"], version))
        script = self.script_for(module, version)
        objects = [(kind, name.replace(VERSION_TOKEN, str(version))) for kind, name in module["objects"]]
        stale = [rule for rule in rules if str(rule.get("S") or "").upper() != script]
        current = [rule for rule in rules if self.rule_matches(rule, module, script)]
        deployed = [row for row in rows if row["version"] == version and row["status"] == "deployed"
                    and row["sha256"] == module["sha256"]]
        old = sorted(set(row["version"] for row in rows if row["status"] == "deployed" and row["version"] != version))
        in_place = current and deployed and not stale and all(name in scripts for _, name in objects)
        # In place is registered only once sessions run it: the rule reaches a
        # session through PREPROC.RESOLUTION, rebuilt by REFRESH, and the old
        # version is retired after that. A batch that failed at its REFRESH left
        # the rule repointed, RESOLUTION on the old version and the old version
        # deployed; this run finishes it (refresh, then retire) instead of
        # calling it registered.
        if in_place and not old and self.resolved(module, script):
            self.record_module(module, version)
            return EXIT_OK, None if quiet else "%s is registered with the SQL preprocessor framework (%s)" % (
                module["label"], script)
        if in_place:
            statements = [BYPASS, "EXECUTE SCRIPT PREPROC.REFRESH;"]
            statements += ["EXECUTE SCRIPT PREPROC.MODULE_RETIRE(%s, %d);" % (sql_literal(module["name"]), number)
                           for number in old]
            return self.deploy(module, version, script, objects, rows, old, statements)
        statements = [BYPASS, module["text"].replace(VERSION_TOKEN, str(version))]
        statements.append("EXECUTE SCRIPT PREPROC.RULE_ENSURE(%s, %s, %s, %s, %s, NULL, TRUE);" % tuple(
            sql_literal(value) for value in (module["scope_type"], module["scope_value"], module["phase"], script,
                                             module["function"])))
        statements.append("EXECUTE SCRIPT PREPROC.MODULE_REGISTER(%s, %d, %s, %s, %s, %s, %s, %s, %s, NULL, %s, %s);"
                          % (sql_literal(module["name"]), version, self.nullable(module["source_repo"]),
                             self.nullable(module["source_ref"]), sql_literal(module["sha256"]), sql_literal(script),
                             sql_literal(module["function"]), sql_literal(module["phase"]),
                             sql_literal(module["deploy_mode"] or ("kit-generated" if module["generated"]
                                                                   else "library-deployed")),
                             self.nullable((note or "")[:NOTE_MAX] or None),
                             sql_literal("\n".join("%s|%s" % item for item in objects))))
        statements += ["EXECUTE SCRIPT PREPROC.RULE_DROP(%d, TRUE);" % int(rule.get("ID")) for rule in stale]
        statements.append("EXECUTE SCRIPT PREPROC.REFRESH;")
        statements += ["EXECUTE SCRIPT PREPROC.MODULE_RETIRE(%s, %d);" % (sql_literal(module["name"]), number)
                       for number in old]
        statements += self.half_made(module, rules, rows, scripts, keep=version)[1]
        return self.deploy(module, version, script, objects, rows, old, statements)

    def deploy(self, module, version, script, objects, rows, old, statements):
        """Run register()'s batch, read back what the database shows, record it."""
        try:
            self.db.run("\n".join(statements), timeout=MODULE_TIMEOUT)
        except SqlError as error:
            self.discard_half_made(module)
            return EXIT_FAILED, "%s could not be registered with the SQL preprocessor framework: %s" % (
                module["label"], error)
        # Registered is what the database shows now, not what exapump's exit
        # code said: the statements above can all answer OK and still leave no
        # module behind (a script body that swallowed the rest of the batch).
        # Read back the provenance row, the rule and every script; a module that
        # is not all there is a failure, and the kit's record of it goes, so
        # nothing reads the manifest as "JSON queries work" while they do not.
        missing = self.missing_after_register(module, version, script, objects)
        if missing:
            self.record_module(module, remove=True)
            self.discard_half_made(module)
            return EXIT_FAILED, "%s could not be registered with the SQL preprocessor framework: the database" \
                " shows %s after the deploy" % (module["label"], "; ".join(missing))
        self.record_module(module, version)
        if old or any(row["status"] == "retired" for row in rows):
            self.reclaim(module)
        moved = " (version %s retired)" % ", ".join(str(n) for n in old) if old else ""
        return EXIT_OK, "%s registered with the SQL preprocessor framework: %s for %s %s%s" % (
            module["label"], script, module["scope_type"].lower(), module["scope_value"], moved)

    def resolved(self, module, script):
        """True when PREPROC.RESOLUTION, what MASTER and the profiles dispatch
        from, has caught up with this module's rule: no row names another
        version of it, and a rule for every user (ROLE PUBLIC) has its rows."""
        rows = self.db.run(BYPASS + "\nSELECT DISTINCT SCRIPT_NAME AS S FROM PREPROC.RESOLUTION;")
        names = set(str(row.get("S") or "").upper() for row in (rows[-1] if rows else []))
        if any(script_version(name, module["base"]) is not None and name != script for name in names):
            return False
        return script in names or (module["scope_type"], module["scope_value"]) != ("ROLE", "PUBLIC")

    def missing_after_register(self, module, version, script, objects):
        """What register() deployed and the database does not show: [] when the
        module is all there (its deployed provenance row with this content, its
        rule on this version, every script it creates)."""
        rules, rows = self.module_state(module)
        scripts = self.framework_scripts()
        missing = []
        if not any(row["version"] == version and row["status"] == "deployed" and row["sha256"] == module["sha256"]
                   for row in rows):
            missing.append("no deployed %s version %d in PREPROC.MODULES" % (module["name"], version))
        if not any(self.rule_matches(rule, module, script) for rule in rules):
            missing.append("no rule for %s in PREPROC.CONFIG" % script)
        absent = [name for _, name in objects if name not in scripts]
        if absent:
            missing.append("no script %s" % ", ".join(absent))
        return missing

    def half_made(self, module, rules, rows, scripts, keep=None):
        """A deploy of this module that never registered (a batch that failed before MODULE_REGISTER): a version
        its rules or scripts carry with no provenance row, which MODULE_RECLAIM can never drop. Returns the
        statements that drop it, (its rules, its scripts); ``keep`` is the version being deployed now."""
        known = set(row["version"] for row in rows)
        seen = set(script_version(name, module["base"]) for name in scripts)
        seen |= set(script_version(str(rule.get("S") or "").upper(), module["base"]) for rule in rules)
        versions = [number for number in sorted(seen - known - {None, keep})
                    if module["generated"] or number == module["version"]]
        rule_drops = ["EXECUTE SCRIPT PREPROC.RULE_DROP(%d, TRUE);" % int(rule.get("ID")) for rule in rules
                      if script_version(str(rule.get("S") or "").upper(), module["base"]) in versions]
        names = [template.replace(VERSION_TOKEN, str(number)) for number in versions
                 for template in module["templates"]]
        return rule_drops, ["DROP SCRIPT IF EXISTS %s;" % name for name in names if name in scripts]

    def discard_half_made(self, module):
        """After a register that failed: the new version's rule and scripts go again when it never registered, so no
        second rule of the module goes live at the next REFRESH. Best effort; the next register drops what is left."""
        try:
            rules, rows = self.module_state(module)
            rule_drops, script_drops = self.half_made(module, rules, rows, self.framework_scripts())
            if rule_drops or script_drops:
                self.db.run("\n".join([BYPASS] + rule_drops + script_drops), timeout=MODULE_TIMEOUT)
        except SqlError as error:
            self.db._log("module cleanup for %s: %s" % (module["name"], error))

    @staticmethod
    def nullable(value):
        return "NULL" if value is None else sql_literal(value)

    def reclaim(self, module):
        """Drop retired versions nothing points at any more (the framework's guarded
        MODULE_RECLAIM refuses a version a rule or a live profile still names).
        Housekeeping: a refusal or an error is logged, never reported as a fault."""
        try:
            if "PREPROC.MODULE_RECLAIM" not in self.framework_scripts():
                return
            _, rows = self.module_state(module)
            for row in rows:
                if row["status"] == "retired":
                    self.db.run("%s\nEXECUTE SCRIPT PREPROC.MODULE_RECLAIM(%s, %d);"
                                % (BYPASS, sql_literal(module["name"]), row["version"]))
        except SqlError as error:
            self.db._log("module reclaim for %s: %s" % (module["name"], error))

    def retire(self, addon):
        module = load_module(addon, self.modules_dir, artifact=None)
        if module is None:
            return EXIT_SKIPPED, "%s has no module folder; there is nothing to retire" % addon
        why = self.gate(module, registering=False)
        if why:
            self.record_module(module, remove=True)
            return EXIT_SKIPPED, why
        rules, rows = self.module_state(module)
        deployed = [row["version"] for row in rows if row["status"] == "deployed"]
        leftover = self.half_made(module, rules, rows, self.framework_scripts())[1]
        if not rules and not deployed and not leftover:
            self.record_module(module, remove=True)
            return EXIT_OK, None
        statements = [BYPASS]
        statements += ["EXECUTE SCRIPT PREPROC.RULE_DROP(%d, TRUE);" % int(rule.get("ID")) for rule in rules]
        statements.append("EXECUTE SCRIPT PREPROC.REFRESH;")
        statements += ["EXECUTE SCRIPT PREPROC.MODULE_RETIRE(%s, %d);" % (sql_literal(module["name"]), number)
                       for number in deployed]
        statements += leftover
        try:
            self.db.run("\n".join(statements), timeout=MODULE_TIMEOUT)
        except SqlError as error:
            return EXIT_FAILED, "%s could not be retired from the SQL preprocessor framework: %s" % (
                module["label"], error)
        self.record_module(module, remove=True)
        self.reclaim(module)
        return EXIT_OK, "%s retired from the SQL preprocessor framework" % module["label"]

    def generate(self, module, out):
        """Run a generated module's [kit] generator, for the framework's own pass."""
        fill = {"{python}": sys.executable, "{kit_root}": os.path.dirname(os.path.dirname(HERE)),
                "{home}": os.path.dirname(os.path.abspath(self.args.manifest)), "{out}": out,
                "{exapump}": self.args.exapump, "{profile}": self.args.profile}
        argv = []
        for item in module["generator"]:
            item = str(item)
            for key, value in fill.items():
                item = item.replace(key, value)
            argv.append(item)
        try:
            done = subprocess.run(argv, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=MODULE_TIMEOUT)
        except (OSError, subprocess.TimeoutExpired) as error:
            raise ModuleError("its module generator did not run: %s" % error)
        self.db._log(done.stderr.decode("utf-8", "replace"))
        if done.returncode != 0 or not os.path.isfile(out):
            raise ModuleError("its module generator exited with %s" % done.returncode)
        note = done.stdout.decode("utf-8", "replace").strip().splitlines()
        return note[-1] if note else None

    def register_installed(self):
        """The framework's pass: every installed add-on with a folder, registered.
        Silent when nothing changed; a problem is a warning, never a failure of
        the framework."""
        for addon in installed_addons(self.manifest_doc(), self.modules_dir):
            try:
                module = load_module(addon, self.modules_dir, artifact=None)
                if module["generated"]:
                    if not module["generator"]:
                        emit("INFO", "%s registers its module when it is next installed or updated"
                             % module["label"])
                        continue
                    with tempfile.TemporaryDirectory(prefix="exakit-module-") as temp:
                        out = os.path.join(temp, "artifact.sql")
                        note = self.generate(module, out)
                        code, text = self.register(addon, artifact=out, note=note, quiet=True)
                else:
                    code, text = self.register(addon, quiet=True)
            except (ModuleError, SqlError, state.StateError) as error:
                code, text = EXIT_FAILED, "%s could not be registered with the SQL preprocessor framework: %s" % (
                    addon, error)
            if text:
                emit("OK" if code == EXIT_OK else ("INFO" if code == EXIT_SKIPPED else "WARN"), text)


def run_module_command(args):
    modules = Modules(args)
    try:
        with modules.locked():
            if args.command == "register-module":
                code, text = modules.register(args.addon, artifact=args.artifact or None, note=args.note or None)
            else:
                code, text = modules.retire(args.addon)
    except ModuleError as error:
        code, text = EXIT_FAILED, str(error)
    except SqlError as error:
        code, text = EXIT_FAILED, "the database could not be read: %s" % error
    except state.StateError as error:
        code, text = EXIT_FAILED, "the install manifest could not be updated: %s" % error
    if text:
        emit({EXIT_OK: "OK", EXIT_SKIPPED: "INFO"}.get(code, "FAIL"), text)
    return code


def now():
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _parser():
    parser = argparse.ArgumentParser(prog="manage.py", description="SQL preprocessor framework setup.")
    sub = parser.add_subparsers(dest="command")
    derive = sub.add_parser("derive")
    derive.add_argument("--package", required=True)
    derive.add_argument("--out", default="")
    for name in ("ensure", "inspect", "register-module", "retire-module"):
        cmd = sub.add_parser(name)
        cmd.add_argument("--exapump", required=True)
        cmd.add_argument("--profile", required=True)
        cmd.add_argument("--manifest", required=True)
        cmd.add_argument("--log", default="")
        # Where the add-on module folders are; tests point it elsewhere.
        cmd.add_argument("--modules-dir", default="", help=argparse.SUPPRESS)
        if name in ("register-module", "retire-module"):
            cmd.add_argument("addon")
        if name == "register-module":
            cmd.add_argument("--artifact", default="")
            cmd.add_argument("--note", default="")
        if name == "ensure":
            cmd.add_argument("--admin-user", required=True)
            cmd.add_argument("--pin-version", required=True)
            cmd.add_argument("--pin-ref", required=True)
            cmd.add_argument("--pin-sha256", required=True)
            cmd.add_argument("--pin-core-sha256", default="")
            cmd.add_argument("--package", default="")
            cmd.add_argument("--opt-in-command", default="")
    return parser


def main(argv=None):
    parser = _parser()
    args = parser.parse_args(argv)
    if not args.command:
        parser.print_usage(sys.stderr)
        return state.EXIT_USAGE
    if args.command == "derive":
        # The maintainer's and CI's view of the core-only package: its digest
        # (the value pinned as sha256.core-only) and what it leaves out.
        with open(args.package, encoding="utf-8", newline="") as handle:
            body, removed = core_only(handle.read())
        if args.out:
            with open(args.out, "w", encoding="utf-8", newline="") as handle:
                handle.write(body)
        print(json.dumps({"sha256": sha256_text(body), "left_out": removed}))
        return EXIT_OK
    if args.command in ("register-module", "retire-module"):
        return run_module_command(args)
    manager = Preprocessor(args)
    if args.command == "inspect":
        try:
            found = manager.inspect()
        except SqlError as error:
            print(json.dumps({"ok": False, "error": str(error)}))
            return EXIT_FAILED
        found["record"] = manager.record()
        print(json.dumps(dict(found, ok=True), indent=2))
        return EXIT_OK
    if not re.match(r"^[0-9a-fA-F]{64}$", args.pin_sha256) or (
            args.pin_core_sha256 and not re.match(r"^[0-9a-fA-F]{64}$", args.pin_core_sha256)):
        emit("FAIL", "the pinned SHA-256 is not a 64-character hex digest")
        return state.EXIT_USAGE
    try:
        code = manager.ensure()
    except Outcome as outcome:
        # Asking for the package is a step of a normal fresh install, not a
        # failure: the caller fetches it and calls again.
        emit("INFO" if outcome.code == EXIT_NEED_PACKAGE else "FAIL", str(outcome))
        return outcome.code
    except state.StateError as error:
        emit("FAIL", "the install manifest could not be updated: %s" % error)
        return EXIT_FAILED
    if code == EXIT_OK:
        # A framework that arrives after its add-ons (a kit update) registers
        # them now; on every later pass this is one read and silent.
        modules = Modules(args)
        try:
            with modules.locked():
                modules.register_installed()
        except (SqlError, state.StateError) as error:
            emit("WARN", "Add-on modules could not be checked against the framework: %s" % error)
    return code


if __name__ == "__main__":
    sys.exit(main())
