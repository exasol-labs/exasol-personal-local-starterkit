-- examples.sql - questions the bank_marketing dataset answers, one query each.
-- Every query runs as it stands against the loaded BANKMKT schema (the kit's tests
-- run them all). Read-only: the MCP user can run them too.

-- 1. How many clients subscribed a term deposit?
SELECT SUBSCRIBED, COUNT(*) AS CLIENTS, ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) AS PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY SUBSCRIBED
ORDER BY SUBSCRIBED;

-- 2. Subscription rate by job.
SELECT JOB, COUNT(*) AS CLIENTS, ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY JOB
ORDER BY SUBSCRIBED_PCT DESC;

-- 3. Subscription rate by age band.
SELECT CASE WHEN AGE < 30 THEN 'under 30' WHEN AGE < 40 THEN '30-39' WHEN AGE < 50 THEN '40-49'
            WHEN AGE < 60 THEN '50-59' ELSE '60 and over' END AS AGE_BAND,
       COUNT(*) AS CLIENTS, ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY 1
ORDER BY 1;

-- 4. Does a previous campaign's success carry over?
SELECT PREVIOUS_OUTCOME, COUNT(*) AS CLIENTS, ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY PREVIOUS_OUTCOME
ORDER BY SUBSCRIBED_PCT DESC;

-- 5. Subscription rate by the month of the last contact.
SELECT LAST_CONTACT_MONTH, COUNT(*) AS CLIENTS, ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY LAST_CONTACT_MONTH
ORDER BY CLIENTS DESC;

-- 6. Does calling more often help?
SELECT LEAST(CAMPAIGN_CONTACTS, 6) AS CONTACTS_THIS_CAMPAIGN, COUNT(*) AS CLIENTS,
       ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY LEAST(CAMPAIGN_CONTACTS, 6)
ORDER BY CONTACTS_THIS_CAMPAIGN;

-- 7. Loans and subscriptions.
SELECT HOUSING_LOAN, PERSONAL_LOAN, COUNT(*) AS CLIENTS, ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY HOUSING_LOAN, PERSONAL_LOAN
ORDER BY HOUSING_LOAN, PERSONAL_LOAN;

-- 8. Balance of subscribers against the others.
SELECT SUBSCRIBED, ROUND(AVG(BALANCE)) AS AVG_BALANCE, MEDIAN(BALANCE) AS MEDIAN_BALANCE
FROM BANKMKT.BANK_CLIENTS
GROUP BY SUBSCRIBED
ORDER BY SUBSCRIBED;

-- 9. The leak: call duration of subscribers against the others (known only after the call).
SELECT SUBSCRIBED, ROUND(AVG(CALL_DURATION)) AS AVG_SECONDS, MEDIAN(CALL_DURATION) AS MEDIAN_SECONDS
FROM BANKMKT.BANK_CLIENTS
GROUP BY SUBSCRIBED
ORDER BY SUBSCRIBED;

-- 10. Subscription rate by education and marital status.
SELECT EDUCATION, MARITAL, COUNT(*) AS CLIENTS, ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY EDUCATION, MARITAL
ORDER BY SUBSCRIBED_PCT DESC;

-- 11. Contact channel and outcome.
SELECT CONTACT_TYPE, COUNT(*) AS CLIENTS, ROUND(100 * AVG(SUBSCRIBED), 1) AS SUBSCRIBED_PCT
FROM BANKMKT.BANK_CLIENTS
GROUP BY CONTACT_TYPE
ORDER BY CLIENTS DESC;
