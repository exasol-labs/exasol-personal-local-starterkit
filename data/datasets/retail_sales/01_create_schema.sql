-- 01_create_schema.sql - retail sales dataset schema.
-- One table, RETAIL_SALES.RETAIL_SALES, from data/retail_sales.csv: one row per
-- sale. Idempotent: CREATE OR REPLACE TABLE can be re-run (exakit data-load --force).

CREATE SCHEMA IF NOT EXISTS RETAIL_SALES;
OPEN SCHEMA RETAIL_SALES;

CREATE OR REPLACE TABLE RETAIL_SALES (
    TRANSACTION_ID   DECIMAL(9,0)  NOT NULL,
    SALE_DATE        DATE          NOT NULL,
    CUSTOMER_ID      VARCHAR(20)   NOT NULL,
    GENDER           VARCHAR(10)   NOT NULL,
    AGE              DECIMAL(3,0)  NOT NULL,
    PRODUCT_CATEGORY VARCHAR(30)   NOT NULL,
    QUANTITY         DECIMAL(9,0)  NOT NULL,
    PRICE_PER_UNIT   DECIMAL(12,2) NOT NULL,
    TOTAL_AMOUNT     DECIMAL(14,2) NOT NULL,
    CONSTRAINT RETAIL_SALES_PK PRIMARY KEY (TRANSACTION_ID)
);

COMMENT ON TABLE  RETAIL_SALES IS 'One retail sale (1,000 rows). PK transaction_id.';
COMMENT ON COLUMN RETAIL_SALES.TRANSACTION_ID IS 'Sale id (PK)';
COMMENT ON COLUMN RETAIL_SALES.SALE_DATE IS 'Date of the sale';
COMMENT ON COLUMN RETAIL_SALES.CUSTOMER_ID IS 'Customer who bought';
COMMENT ON COLUMN RETAIL_SALES.GENDER IS 'Customer gender';
COMMENT ON COLUMN RETAIL_SALES.AGE IS 'Customer age in years';
COMMENT ON COLUMN RETAIL_SALES.PRODUCT_CATEGORY IS 'Beauty, Clothing or Electronics';
COMMENT ON COLUMN RETAIL_SALES.QUANTITY IS 'Units sold';
COMMENT ON COLUMN RETAIL_SALES.PRICE_PER_UNIT IS 'Price of one unit';
COMMENT ON COLUMN RETAIL_SALES.TOTAL_AMOUNT IS 'Quantity times price per unit';
