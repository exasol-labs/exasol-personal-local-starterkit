-- examples.sql - questions the banking_complaints dataset answers, one query each.
-- Every query runs as it stands against the loaded BANKING schema (the kit's tests
-- check them all). Read-only: the MCP user can run them too.

-- 1. How complaints were closed, and what share got monetary relief.
SELECT COMPANY_RESPONSE, COUNT(*) AS COMPLAINTS,
       ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) AS PCT
FROM BANKING.BANKING_RESPONSES
GROUP BY COMPANY_RESPONSE
ORDER BY COMPLAINTS DESC;

-- 2. Monetary relief rate by product.
SELECT PRODUCT, COUNT(*) AS COMPLAINTS, SUM(MONETARY_RELIEF) AS WITH_RELIEF,
       ROUND(100 * AVG(MONETARY_RELIEF), 1) AS RELIEF_PCT
FROM BANKING.BANKING_COMPLAINTS
GROUP BY PRODUCT
ORDER BY RELIEF_PCT DESC;

-- 3. Complaints received per day.
SELECT DATE_RECEIVED, COUNT(*) AS COMPLAINTS
FROM BANKING.BANKING_COMPLAINTS
GROUP BY DATE_RECEIVED
ORDER BY DATE_RECEIVED;

-- 4. The ten companies with the most complaints, and how often they paid.
SELECT COMPANY, COUNT(*) AS COMPLAINTS, ROUND(100 * AVG(MONETARY_RELIEF), 1) AS RELIEF_PCT
FROM BANKING.BANKING_COMPLAINTS
GROUP BY COMPANY
ORDER BY COMPLAINTS DESC, COMPANY
LIMIT 10;

-- 5. The commonest issues per product.
SELECT PRODUCT, ISSUE, COUNT(*) AS COMPLAINTS
FROM BANKING.BANKING_COMPLAINTS
GROUP BY PRODUCT, ISSUE
QUALIFY ROW_NUMBER() OVER (PARTITION BY PRODUCT ORDER BY COUNT(*) DESC, ISSUE) <= 3
ORDER BY PRODUCT, COMPLAINTS DESC;

-- 6. Issues that most often end in monetary relief (at least 30 complaints).
SELECT ISSUE, COUNT(*) AS COMPLAINTS, ROUND(100 * AVG(MONETARY_RELIEF), 1) AS RELIEF_PCT
FROM BANKING.BANKING_COMPLAINTS
GROUP BY ISSUE
HAVING COUNT(*) >= 30
ORDER BY RELIEF_PCT DESC, ISSUE
LIMIT 10;

-- 7. Complaints from servicemembers and older Americans against the rest.
SELECT CASE WHEN TAGS IS NULL THEN 'no tag' ELSE TAGS END AS TAG, COUNT(*) AS COMPLAINTS,
       ROUND(100 * AVG(MONETARY_RELIEF), 1) AS RELIEF_PCT
FROM BANKING.BANKING_COMPLAINTS
GROUP BY 1
ORDER BY COMPLAINTS DESC;

-- 8. Channels: how complaints arrive.
SELECT SUBMITTED_VIA, COUNT(*) AS COMPLAINTS
FROM BANKING.BANKING_COMPLAINTS
GROUP BY SUBMITTED_VIA
ORDER BY COMPLAINTS DESC;

-- 9. The states with the most complaints per product.
SELECT CONSUMER_STATE, PRODUCT, COUNT(*) AS COMPLAINTS
FROM BANKING.BANKING_COMPLAINTS
WHERE CONSUMER_STATE IS NOT NULL
GROUP BY CONSUMER_STATE, PRODUCT
QUALIFY ROW_NUMBER() OVER (PARTITION BY PRODUCT ORDER BY COUNT(*) DESC, CONSUMER_STATE) <= 5
ORDER BY PRODUCT, COMPLAINTS DESC;

-- 10. Days from receipt to the company, and how often the answer was on time.
SELECT PRODUCT, MEDIAN(DAYS_BETWEEN(DATE_SENT_TO_COMPANY, DATE_RECEIVED)) AS MEDIAN_DAYS_TO_COMPANY,
       ROUND(100 * AVG(TIMELY), 1) AS TIMELY_PCT
FROM BANKING.BANKING_COMPLAINTS
GROUP BY PRODUCT
ORDER BY PRODUCT;

-- 11. The companies' public responses (a few set phrases), with the relief rate behind each.
SELECT COALESCE(COMPANY_PUBLIC_RESPONSE, '(none)') AS PUBLIC_RESPONSE, COUNT(*) AS COMPLAINTS,
       ROUND(100 * AVG(MONETARY_RELIEF), 1) AS RELIEF_PCT
FROM BANKING.BANKING_COMPLAINTS
GROUP BY 1
ORDER BY COMPLAINTS DESC;

-- 12. Sub-issues that mention fees, by product - the kind of question the text step answers at scale.
SELECT PRODUCT, COUNT(*) AS COMPLAINTS,
       SUM(CASE WHEN UPPER(ISSUE || ' ' || COALESCE(SUB_ISSUE, '')) LIKE '%FEE%' THEN 1 ELSE 0 END) AS ABOUT_FEES
FROM BANKING.BANKING_COMPLAINTS
GROUP BY PRODUCT
ORDER BY PRODUCT;
