-- examples.sql - questions the pharma_trials dataset answers, one query each.
-- Every query runs as it stands against the loaded PHARMA schema (the kit's tests
-- run them all). Read-only: the MCP user can run them too.

-- 1. How many trials ended each way, and what share was terminated early?
SELECT OVERALL_STATUS, COUNT(*) AS TRIALS,
       ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) AS PCT
FROM PHARMA.PHARMA_TRIALS
GROUP BY OVERALL_STATUS
ORDER BY TRIALS DESC;

-- 2. Termination rate by phase.
SELECT PHASE, COUNT(*) AS TRIALS, SUM(TERMINATED) AS TERMINATED,
       ROUND(100 * AVG(TERMINATED), 1) AS TERMINATED_PCT
FROM PHARMA.PHARMA_TRIALS
GROUP BY PHASE
ORDER BY TERMINATED_PCT DESC;

-- 3. Trials started per year and quarter.
SELECT YEAR(START_DATE) AS START_YEAR, CEIL(MONTH(START_DATE) / 3) AS START_QUARTER, COUNT(*) AS TRIALS
FROM PHARMA.PHARMA_TRIALS
GROUP BY YEAR(START_DATE), CEIL(MONTH(START_DATE) / 3)
ORDER BY START_YEAR, START_QUARTER;

-- 4. The ten sponsors that ran the most trials, with their termination rate.
SELECT LEAD_SPONSOR, COUNT(*) AS TRIALS, ROUND(100 * AVG(TERMINATED), 1) AS TERMINATED_PCT
FROM PHARMA.PHARMA_TRIALS
GROUP BY LEAD_SPONSOR
ORDER BY TRIALS DESC, LEAD_SPONSOR
LIMIT 10;

-- 5. The most studied conditions.
SELECT c.CONDITION_NAME, COUNT(*) AS TRIALS
FROM PHARMA.PHARMA_CONDITIONS c
GROUP BY c.CONDITION_NAME
ORDER BY TRIALS DESC, c.CONDITION_NAME
LIMIT 15;

-- 6. Does blinding go with finishing? Termination rate by masking.
SELECT COALESCE(MASKING, '(not given)') AS MASKING, COUNT(*) AS TRIALS,
       ROUND(100 * AVG(TERMINATED), 1) AS TERMINATED_PCT
FROM PHARMA.PHARMA_TRIALS
GROUP BY COALESCE(MASKING, '(not given)')
ORDER BY TRIALS DESC;

-- 7. Median enrollment and median duration (start to primary completion) by phase and outcome.
SELECT PHASE, OVERALL_STATUS,
       MEDIAN(ENROLLMENT) AS MEDIAN_ENROLLMENT,
       MEDIAN(DAYS_BETWEEN(PRIMARY_COMPLETION_DATE, START_DATE)) AS MEDIAN_DAYS
FROM PHARMA.PHARMA_TRIALS
GROUP BY PHASE, OVERALL_STATUS
ORDER BY PHASE, OVERALL_STATUS;

-- 8. Intervention types: how many trials test each, and how often those trials stop early.
SELECT i.INTERVENTION_TYPE, COUNT(DISTINCT i.NCT_ID) AS TRIALS,
       ROUND(100 * AVG(t.TERMINATED), 1) AS TERMINATED_PCT
FROM PHARMA.PHARMA_INTERVENTIONS i
JOIN PHARMA.PHARMA_TRIALS t ON t.NCT_ID = i.NCT_ID
GROUP BY i.INTERVENTION_TYPE
ORDER BY TRIALS DESC;

-- 9. Placebo-controlled trials against the rest.
SELECT CASE WHEN p.NCT_ID IS NOT NULL THEN 'placebo-controlled' ELSE 'no placebo arm' END AS DESIGN,
       COUNT(*) AS TRIALS, ROUND(100 * AVG(t.TERMINATED), 1) AS TERMINATED_PCT
FROM PHARMA.PHARMA_TRIALS t
LEFT JOIN (SELECT DISTINCT NCT_ID FROM PHARMA.PHARMA_INTERVENTIONS
           WHERE UPPER(INTERVENTION_NAME) LIKE '%PLACEBO%') p ON p.NCT_ID = t.NCT_ID
GROUP BY 1
ORDER BY TRIALS DESC;

-- 10. Why trials stop: the commonest words in the stop reasons (read, never a model feature).
SELECT CASE
         WHEN UPPER(WHY_STOPPED) LIKE '%BUSINESS%' OR UPPER(WHY_STOPPED) LIKE '%SPONSOR DECISION%' OR UPPER(WHY_STOPPED) LIKE '%STRATEG%' THEN 'business or strategy'
         WHEN UPPER(WHY_STOPPED) LIKE '%ENROL%' OR UPPER(WHY_STOPPED) LIKE '%RECRUIT%' OR UPPER(WHY_STOPPED) LIKE '%ACCRUAL%' THEN 'enrollment'
         WHEN UPPER(WHY_STOPPED) LIKE '%EFFICACY%' OR UPPER(WHY_STOPPED) LIKE '%FUTILITY%' THEN 'efficacy or futility'
         WHEN UPPER(WHY_STOPPED) LIKE '%SAFETY%' OR UPPER(WHY_STOPPED) LIKE '%ADVERSE%' THEN 'safety'
         ELSE 'other'
       END AS REASON,
       COUNT(*) AS TRIALS
FROM PHARMA.PHARMA_STOP_REASONS
GROUP BY 1
ORDER BY TRIALS DESC;

-- 11. Trials with posted results, by outcome.
SELECT OVERALL_STATUS, SUM(HAS_RESULTS) AS WITH_RESULTS, COUNT(*) AS TRIALS,
       ROUND(100 * AVG(HAS_RESULTS), 1) AS WITH_RESULTS_PCT
FROM PHARMA.PHARMA_TRIALS
GROUP BY OVERALL_STATUS
ORDER BY OVERALL_STATUS;

-- 12. Summaries that mention a biomarker, by phase - the kind of question the text step answers at scale.
SELECT PHASE, COUNT(*) AS TRIALS,
       SUM(CASE WHEN UPPER(BRIEF_SUMMARY) LIKE '%BIOMARKER%' THEN 1 ELSE 0 END) AS MENTIONS_BIOMARKER
FROM PHARMA.PHARMA_TRIALS
GROUP BY PHASE
ORDER BY PHASE;

-- 13. Do trials run with collaborators stop early less often? Termination rate by the number of collaborators.
SELECT CASE WHEN s.COLLABORATORS = 0 THEN 'none' WHEN s.COLLABORATORS = 1 THEN 'one' ELSE 'two or more' END AS COLLABORATORS,
       COUNT(*) AS TRIALS, ROUND(100 * AVG(t.TERMINATED), 1) AS TERMINATED_PCT
FROM PHARMA.PHARMA_TRIALS t
JOIN (SELECT NCT_ID, SUM(CASE WHEN SPONSOR_ROLE = 'COLLABORATOR' THEN 1 ELSE 0 END) AS COLLABORATORS
      FROM PHARMA.PHARMA_SPONSORS GROUP BY NCT_ID) s ON s.NCT_ID = t.NCT_ID
GROUP BY 1
ORDER BY 1;

-- 14. Eligibility criteria that exclude pregnancy, by phase - a second text column to search.
SELECT PHASE, COUNT(*) AS TRIALS,
       SUM(CASE WHEN UPPER(ELIGIBILITY_CRITERIA) LIKE '%PREGNAN%' THEN 1 ELSE 0 END) AS MENTIONS_PREGNANCY,
       ROUND(AVG(LENGTH(ELIGIBILITY_CRITERIA)), 0) AS AVG_CRITERIA_CHARS
FROM PHARMA.PHARMA_TRIALS
GROUP BY PHASE
ORDER BY PHASE;
