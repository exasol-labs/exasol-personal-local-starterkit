-- examples.sql - questions the walmart_sales dataset answers, one query each.
-- Every query runs as it stands against the loaded WALMART schema (the kit's tests
-- run them all). Read-only: the MCP user can run them too.

-- 1. Which stores sell the most?
SELECT STORE, ROUND(SUM(WEEKLY_SALES) / 1e6, 1) AS SALES_MILLIONS
FROM WALMART.WEEKLY_SALES
GROUP BY STORE
ORDER BY SALES_MILLIONS DESC
LIMIT 10;

-- 2. Do holiday weeks sell more?
SELECT HOLIDAY_WEEK, COUNT(*) AS WEEKS, ROUND(AVG(WEEKLY_SALES), 0) AS AVG_SALES
FROM WALMART.WEEKLY_SALES
GROUP BY HOLIDAY_WEEK
ORDER BY HOLIDAY_WEEK;

-- 3. Sales by month, all stores together.
SELECT TO_CHAR(WEEK_DATE, 'YYYY-MM') AS SALES_MONTH, ROUND(SUM(WEEKLY_SALES) / 1e6, 1) AS SALES_MILLIONS
FROM WALMART.WEEKLY_SALES
GROUP BY 1
ORDER BY 1;

-- 4. Is a store's sales tied to local unemployment?
SELECT CASE WHEN UNEMPLOYMENT < 6 THEN 'under 6%' WHEN UNEMPLOYMENT < 8 THEN '6-8%'
            WHEN UNEMPLOYMENT < 10 THEN '8-10%' ELSE '10% and over' END AS UNEMPLOYMENT_BAND,
       COUNT(*) AS WEEKS, ROUND(AVG(WEEKLY_SALES), 0) AS AVG_SALES
FROM WALMART.WEEKLY_SALES
GROUP BY 1
ORDER BY 1;

-- 5. How often does each store beat its usual week?
SELECT STORE, SUM(ABOVE_STORE_MEDIAN) AS STRONG_WEEKS, COUNT(*) AS WEEKS
FROM WALMART.WEEKLY_SALES
GROUP BY STORE
ORDER BY STORE
LIMIT 10;

-- 6. Which months have the most strong weeks?
SELECT EXTRACT(MONTH FROM WEEK_DATE) AS MONTH_NO, ROUND(100 * AVG(ABOVE_STORE_MEDIAN), 1) AS STRONG_WEEK_PCT
FROM WALMART.WEEKLY_SALES
GROUP BY 1
ORDER BY STRONG_WEEK_PCT DESC;

-- 7. Sales by year.
SELECT EXTRACT(YEAR FROM WEEK_DATE) AS SALES_YEAR, ROUND(SUM(WEEKLY_SALES) / 1e6, 1) AS SALES_MILLIONS
FROM WALMART.WEEKLY_SALES
GROUP BY 1
ORDER BY 1;

-- 8. The single best week of every store, top ten.
SELECT STORE, WEEK_DATE, WEEKLY_SALES
FROM WALMART.WEEKLY_SALES
QUALIFY ROW_NUMBER() OVER (PARTITION BY STORE ORDER BY WEEKLY_SALES DESC) = 1
ORDER BY WEEKLY_SALES DESC
LIMIT 10;

-- 9. Do warm weeks sell differently?
SELECT CASE WHEN TEMPERATURE_F < 40 THEN 'under 40F' WHEN TEMPERATURE_F < 60 THEN '40-60F'
            WHEN TEMPERATURE_F < 80 THEN '60-80F' ELSE '80F and over' END AS TEMPERATURE_BAND,
       COUNT(*) AS WEEKS, ROUND(AVG(WEEKLY_SALES), 0) AS AVG_SALES
FROM WALMART.WEEKLY_SALES
GROUP BY 1
ORDER BY 1;

-- 10. Fuel price over time, all stores averaged.
SELECT TO_CHAR(WEEK_DATE, 'YYYY-MM') AS SALES_MONTH, ROUND(AVG(FUEL_PRICE), 3) AS AVG_FUEL_PRICE
FROM WALMART.WEEKLY_SALES
GROUP BY 1
ORDER BY 1;

-- 11. Week-over-week change for store 1, the latest ten weeks.
SELECT WEEK_DATE, WEEKLY_SALES,
       WEEKLY_SALES - LAG(WEEKLY_SALES) OVER (ORDER BY WEEK_DATE) AS CHANGE_FROM_LAST_WEEK
FROM WALMART.WEEKLY_SALES
WHERE STORE = 1
ORDER BY WEEK_DATE DESC
LIMIT 10;
