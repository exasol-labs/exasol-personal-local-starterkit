-- examples.sql - questions the fda_recalls dataset answers, one query each.
-- Every query runs as it stands against the loaded FDA schema (the kit's tests
-- check them all). Read-only: the MCP user can run them too.

-- 1. How the FDA classified the recalls, and the share of each class.
SELECT CLASSIFICATION, COUNT(*) AS RECALLS,
       ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) AS PCT
FROM FDA.FDA_CLASSIFICATIONS
GROUP BY CLASSIFICATION
ORDER BY CLASSIFICATION;

-- 2. Serious (Class I) rate by product type.
SELECT PRODUCT_TYPE, COUNT(*) AS RECALLS, SUM(SERIOUS) AS CLASS_I,
       ROUND(100 * AVG(SERIOUS), 1) AS CLASS_I_PCT
FROM FDA.FDA_RECALLS
GROUP BY PRODUCT_TYPE
ORDER BY CLASS_I_PCT DESC;

-- 3. Recalls reported per month.
SELECT TO_CHAR(REPORT_DATE, 'YYYY-MM') AS REPORT_MONTH, COUNT(*) AS RECALLS, SUM(SERIOUS) AS CLASS_I
FROM FDA.FDA_RECALLS
GROUP BY TO_CHAR(REPORT_DATE, 'YYYY-MM')
ORDER BY REPORT_MONTH;

-- 4. The ten firms with the most recalled products.
SELECT RECALLING_FIRM, COUNT(*) AS RECALLS, COUNT(DISTINCT EVENT_ID) AS EVENTS,
       ROUND(100 * AVG(SERIOUS), 1) AS CLASS_I_PCT
FROM FDA.FDA_RECALLS
GROUP BY RECALLING_FIRM
ORDER BY RECALLS DESC, RECALLING_FIRM
LIMIT 10;

-- 5. The most frequent reasons, as written.
SELECT REASON_FOR_RECALL, COUNT(*) AS RECALLS
FROM FDA.FDA_RECALLS
GROUP BY REASON_FOR_RECALL
ORDER BY RECALLS DESC, REASON_FOR_RECALL
LIMIT 10;

-- 6. Contamination words in the reason, and how serious those recalls are.
SELECT WORD, COUNT(*) AS RECALLS, ROUND(100 * AVG(SERIOUS), 1) AS CLASS_I_PCT
FROM (SELECT SERIOUS,
             CASE WHEN UPPER(REASON_FOR_RECALL) LIKE '%LISTERIA%' THEN 'listeria'
                  WHEN UPPER(REASON_FOR_RECALL) LIKE '%SALMONELLA%' THEN 'salmonella'
                  WHEN UPPER(REASON_FOR_RECALL) LIKE '%UNDECLARED%' THEN 'undeclared (allergen)'
                  WHEN UPPER(REASON_FOR_RECALL) LIKE '%STERIL%' THEN 'sterility'
                  WHEN UPPER(REASON_FOR_RECALL) LIKE '%CGMP%' THEN 'CGMP deviations'
                  ELSE 'other' END AS WORD
      FROM FDA.FDA_RECALLS)
GROUP BY WORD
ORDER BY RECALLS DESC;

-- 7. Voluntary or not, by product type.
SELECT PRODUCT_TYPE, VOLUNTARY_MANDATED, COUNT(*) AS RECALLS
FROM FDA.FDA_RECALLS
GROUP BY PRODUCT_TYPE, VOLUNTARY_MANDATED
ORDER BY PRODUCT_TYPE, RECALLS DESC;

-- 8. Recall status: how many are still ongoing.
SELECT RECALL_STATUS, COUNT(*) AS RECALLS, SUM(SERIOUS) AS CLASS_I
FROM FDA.FDA_RECALLS
GROUP BY RECALL_STATUS
ORDER BY RECALLS DESC;

-- 9. Days from a firm starting the recall to the FDA reporting it, by class.
SELECT c.CLASSIFICATION, COUNT(*) AS RECALLS,
       ROUND(AVG(DAYS_BETWEEN(r.REPORT_DATE, r.RECALL_INITIATION_DATE)), 1) AS AVG_DAYS
FROM FDA.FDA_RECALLS r
JOIN FDA.FDA_CLASSIFICATIONS c ON c.RECALL_NUMBER = r.RECALL_NUMBER
WHERE r.RECALL_INITIATION_DATE IS NOT NULL
GROUP BY c.CLASSIFICATION
ORDER BY c.CLASSIFICATION;

-- 10. Countries the recalling firms are in.
SELECT FIRM_COUNTRY, COUNT(*) AS RECALLS
FROM FDA.FDA_RECALLS
GROUP BY FIRM_COUNTRY
ORDER BY RECALLS DESC, FIRM_COUNTRY
LIMIT 10;

-- 11. Events that recalled many products at once.
SELECT EVENT_ID, MIN(RECALLING_FIRM) AS FIRM, MIN(PRODUCT_TYPE) AS PRODUCT_TYPE, COUNT(*) AS PRODUCTS
FROM FDA.FDA_RECALLS
GROUP BY EVENT_ID
ORDER BY PRODUCTS DESC, EVENT_ID
LIMIT 10;

-- 12. A text question: Class I food recalls that name an allergen.
SELECT RECALL_NUMBER, RECALLING_FIRM, REASON_FOR_RECALL
FROM FDA.FDA_RECALLS
WHERE PRODUCT_TYPE = 'Food' AND SERIOUS = 1 AND UPPER(REASON_FOR_RECALL) LIKE '%UNDECLARED%'
ORDER BY REPORT_DATE, RECALL_NUMBER
LIMIT 20;
