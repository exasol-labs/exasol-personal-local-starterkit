-- examples.sql - questions the fraud_transactions dataset answers, one query each.
-- Every query runs as it stands against the loaded FRAUD schema (the kit's tests
-- run them all). Read-only: the MCP user can run them too. The first four are the
-- Prepare and Validate checks a fraud rate should pass before anyone trusts it.

-- 1. Is TRANSACTION_ID really one row per transaction? (No: 1,000 repeat.)
SELECT COUNT(*) AS ROWS_TOTAL, COUNT(DISTINCT TRANSACTION_ID) AS TRANSACTIONS,
       COUNT(*) - COUNT(DISTINCT TRANSACTION_ID) AS REPEATED_ROWS
FROM FRAUD.TRANSACTIONS;

-- 2. Which repeats are exact copies, and which disagree with themselves?
SELECT CASE WHEN COUNT(DISTINCT TRANSACTION_AMOUNT || '|' || TRANSACTION_TYPE || '|' || FRAUDULENT) = 1
            THEN 'exact copy' ELSE 'differs' END AS KIND,
       COUNT(*) AS TRANSACTIONS
FROM (SELECT * FROM FRAUD.TRANSACTIONS
      WHERE TRANSACTION_ID IN (SELECT TRANSACTION_ID FROM FRAUD.TRANSACTIONS GROUP BY TRANSACTION_ID HAVING COUNT(*) > 1))
GROUP BY TRANSACTION_ID
ORDER BY 1;

-- 3. How much is missing, column by column?
SELECT COUNT(*) - COUNT(TRANSACTION_AMOUNT) AS NO_AMOUNT, COUNT(*) - COUNT(TRANSACTION_HOUR) AS NO_HOUR,
       COUNT(*) - COUNT(DEVICE_USED) AS NO_DEVICE, COUNT(*) - COUNT(LOCATION) AS NO_CITY,
       COUNT(*) - COUNT(PAYMENT_METHOD) AS NO_PAYMENT_METHOD
FROM FRAUD.TRANSACTIONS;

-- 4. Placeholders that look like values: how often, and how fraudulent?
SELECT 'device' AS FIELD, DEVICE_USED AS VALUE_SEEN, COUNT(*) AS TRANSACTIONS, ROUND(100 * AVG(FRAUDULENT), 2) AS FRAUD_PCT
FROM FRAUD.TRANSACTIONS WHERE DEVICE_USED = 'Unknown Device' GROUP BY DEVICE_USED
UNION ALL
SELECT 'payment method', PAYMENT_METHOD, COUNT(*), ROUND(100 * AVG(FRAUDULENT), 2)
FROM FRAUD.TRANSACTIONS WHERE PAYMENT_METHOD = 'Invalid Method' GROUP BY PAYMENT_METHOD;

-- 5. The fraud rate, counted once per transaction (copies removed).
SELECT COUNT(*) AS TRANSACTIONS, SUM(FRAUDULENT) AS FRAUDS, ROUND(100 * AVG(FRAUDULENT), 2) AS FRAUD_PCT
FROM (SELECT TRANSACTION_ID, MAX(FRAUDULENT) AS FRAUDULENT FROM FRAUD.TRANSACTIONS GROUP BY TRANSACTION_ID);

-- 6. Fraud rate by transaction type.
SELECT TRANSACTION_TYPE, COUNT(*) AS TRANSACTIONS, ROUND(100 * AVG(FRAUDULENT), 2) AS FRAUD_PCT
FROM FRAUD.TRANSACTIONS
GROUP BY TRANSACTION_TYPE
ORDER BY FRAUD_PCT DESC;

-- 7. Does a history of fraud predict more fraud?
SELECT PREVIOUS_FRAUDULENT_TRANSACTIONS, COUNT(*) AS TRANSACTIONS, ROUND(100 * AVG(FRAUDULENT), 2) AS FRAUD_PCT
FROM FRAUD.TRANSACTIONS
GROUP BY PREVIOUS_FRAUDULENT_TRANSACTIONS
ORDER BY PREVIOUS_FRAUDULENT_TRANSACTIONS;

-- 8. Fraud by hour of day (rows without an hour left out).
SELECT TRANSACTION_HOUR, COUNT(*) AS TRANSACTIONS, ROUND(100 * AVG(FRAUDULENT), 2) AS FRAUD_PCT
FROM FRAUD.TRANSACTIONS
WHERE TRANSACTION_HOUR IS NOT NULL
GROUP BY TRANSACTION_HOUR
ORDER BY TRANSACTION_HOUR;

-- 9. Are fraudulent transactions larger?
SELECT FRAUDULENT, COUNT(TRANSACTION_AMOUNT) AS WITH_AMOUNT, ROUND(AVG(TRANSACTION_AMOUNT), 2) AS AVG_AMOUNT,
       ROUND(MEDIAN(TRANSACTION_AMOUNT), 2) AS MEDIAN_AMOUNT
FROM FRAUD.TRANSACTIONS
GROUP BY FRAUDULENT
ORDER BY FRAUDULENT;

-- 10. Busy accounts: many transactions in the last 24 hours.
SELECT CASE WHEN TRANSACTIONS_LAST_24H < 5 THEN '0-4' WHEN TRANSACTIONS_LAST_24H < 10 THEN '5-9' ELSE '10 and more' END AS LAST_24H,
       COUNT(*) AS TRANSACTIONS, ROUND(100 * AVG(FRAUDULENT), 2) AS FRAUD_PCT
FROM FRAUD.TRANSACTIONS
GROUP BY 1
ORDER BY 1;

-- 11. Fraud rate by city.
SELECT COALESCE(LOCATION, '(not recorded)') AS CITY, COUNT(*) AS TRANSACTIONS, ROUND(100 * AVG(FRAUDULENT), 2) AS FRAUD_PCT
FROM FRAUD.TRANSACTIONS
GROUP BY 1
ORDER BY FRAUD_PCT DESC;

-- 12. The users with the most frauds.
SELECT USER_ID, COUNT(*) AS TRANSACTIONS, SUM(FRAUDULENT) AS FRAUDS
FROM FRAUD.TRANSACTIONS
GROUP BY USER_ID
ORDER BY FRAUDS DESC, TRANSACTIONS DESC
LIMIT 10;
