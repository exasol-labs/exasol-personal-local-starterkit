-- examples.sql - questions the pubmed_abstracts dataset answers, one query each.
-- Every query runs as it stands against the loaded PUBMED schema (the kit's tests
-- run them all). Read-only: the MCP user can run them too.

-- 1. How many abstracts are there, and how long are they?
SELECT COUNT(*) AS ABSTRACTS, ROUND(AVG(WORD_COUNT), 0) AS AVG_WORDS, MIN(WORD_COUNT) AS MIN_WORDS, MAX(WORD_COUNT) AS MAX_WORDS
FROM PUBMED.PUBMED_ABSTRACTS;

-- 2. How do the abstracts open?
SELECT COALESCE(FIRST_SECTION, '(unstructured)') AS FIRST_SECTION, COUNT(*) AS ABSTRACTS
FROM PUBMED.PUBMED_ABSTRACTS
GROUP BY 1
ORDER BY ABSTRACTS DESC;

-- 3. Are structured abstracts longer than unstructured ones?
SELECT CASE WHEN FIRST_SECTION IS NULL THEN 'unstructured' ELSE 'structured' END AS KIND,
       COUNT(*) AS ABSTRACTS, ROUND(AVG(WORD_COUNT), 0) AS AVG_WORDS
FROM PUBMED.PUBMED_ABSTRACTS
GROUP BY 1;

-- 4. Which abstracts are about multiple sclerosis?
SELECT ABSTRACT_ID, WORD_COUNT, SUBSTR(ABSTRACT_TEXT, 1, 160) AS OPENING
FROM PUBMED.PUBMED_ABSTRACTS
WHERE ABSTRACT_TEXT LIKE '%multiple sclerosis%' OR ABSTRACT_TEXT LIKE '% MS %'
ORDER BY ABSTRACT_ID
LIMIT 10;

-- 5. How many abstracts mention each of a few common study designs?
SELECT SUM(CASE WHEN LOWER(ABSTRACT_TEXT) LIKE '%randomized%' OR LOWER(ABSTRACT_TEXT) LIKE '%randomised%' THEN 1 ELSE 0 END) AS RANDOMIZED,
       SUM(CASE WHEN LOWER(ABSTRACT_TEXT) LIKE '%placebo%' THEN 1 ELSE 0 END) AS PLACEBO,
       SUM(CASE WHEN LOWER(ABSTRACT_TEXT) LIKE '%retrospective%' THEN 1 ELSE 0 END) AS RETROSPECTIVE,
       SUM(CASE WHEN LOWER(ABSTRACT_TEXT) LIKE '%case report%' THEN 1 ELSE 0 END) AS CASE_REPORT
FROM PUBMED.PUBMED_ABSTRACTS;

-- 6. Which abstracts report a p-value?
SELECT COUNT(*) AS WITH_P_VALUE
FROM PUBMED.PUBMED_ABSTRACTS
WHERE ABSTRACT_TEXT LIKE '%p <%' OR ABSTRACT_TEXT LIKE '%p =%' OR ABSTRACT_TEXT LIKE '%P <%' OR ABSTRACT_TEXT LIKE '%P =%';

-- 7. The ten longest abstracts.
SELECT ABSTRACT_ID, WORD_COUNT, FIRST_SECTION, SUBSTR(ABSTRACT_TEXT, 1, 120) AS OPENING
FROM PUBMED.PUBMED_ABSTRACTS
ORDER BY WORD_COUNT DESC
LIMIT 10;

-- 8. How are abstract lengths spread?
SELECT CASE WHEN WORD_COUNT < 150 THEN 'under 150' WHEN WORD_COUNT < 250 THEN '150-249'
            WHEN WORD_COUNT < 350 THEN '250-349' ELSE '350 and more' END AS LENGTH_BAND,
       COUNT(*) AS ABSTRACTS
FROM PUBMED.PUBMED_ABSTRACTS
GROUP BY 1
ORDER BY 1;

-- 9. Which abstracts name an adverse event or a side effect?
SELECT COUNT(*) AS ABSTRACTS
FROM PUBMED.PUBMED_ABSTRACTS
WHERE LOWER(ABSTRACT_TEXT) LIKE '%adverse event%' OR LOWER(ABSTRACT_TEXT) LIKE '%side effect%';

-- 10. How many abstracts mention interferon?
SELECT COUNT(*) AS ABSTRACTS
FROM PUBMED.PUBMED_ABSTRACTS
WHERE LOWER(ABSTRACT_TEXT) LIKE '%interferon%';
