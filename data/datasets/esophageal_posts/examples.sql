-- examples.sql - questions the esophageal_posts dataset answers, one query each.
-- Every query runs as it stands against the loaded ESOPHAGEAL schema (the kit's tests
-- run them all). Read-only: the MCP user can run them too.

-- 1. Where were the posts published, and what share of each source is negative?
SELECT SOCIAL_NETWORK, COUNT(*) AS POSTS, ROUND(100 * AVG(IS_NEGATIVE), 1) AS NEGATIVE_PCT
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
GROUP BY SOCIAL_NETWORK
ORDER BY POSTS DESC;

-- 2. How is the sentiment split overall?
SELECT SENTIMENT, COUNT(*) AS POSTS, ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) AS PCT
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
GROUP BY SENTIMENT
ORDER BY POSTS DESC;

-- 3. Posts per year and quarter.
SELECT YEAR(CREATED_TIME) AS POST_YEAR, CEIL(MONTH(CREATED_TIME) / 3) AS POST_QUARTER, COUNT(*) AS POSTS
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
GROUP BY YEAR(CREATED_TIME), CEIL(MONTH(CREATED_TIME) / 3)
ORDER BY POST_YEAR, POST_QUARTER;

-- 4. Which kinds of post are most often negative?
SELECT MESSAGE_TYPE, COUNT(*) AS POSTS, SUM(IS_NEGATIVE) AS NEGATIVE, ROUND(100 * AVG(IS_NEGATIVE), 1) AS NEGATIVE_PCT
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
GROUP BY MESSAGE_TYPE
HAVING COUNT(*) >= 100
ORDER BY NEGATIVE_PCT DESC;

-- 5. The websites with the most posts.
SELECT SOURCE_DOMAIN, COUNT(*) AS POSTS
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
WHERE SOURCE_DOMAIN IS NOT NULL
GROUP BY SOURCE_DOMAIN
ORDER BY POSTS DESC
LIMIT 15;

-- 6. Posts per country and language.
SELECT COUNTRY, LANGUAGE, COUNT(*) AS POSTS
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
GROUP BY COUNTRY, LANGUAGE
ORDER BY POSTS DESC
LIMIT 20;

-- 7. Do tweets with media get shared more?
SELECT CASE WHEN MEDIA_TYPES IS NULL THEN 'no media' ELSE 'media' END AS ATTACHED,
       COUNT(*) AS TWEETS, ROUND(AVG(RETWEETS), 2) AS AVG_RETWEETS, ROUND(AVG(FAVORITES), 2) AS AVG_FAVORITES
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
WHERE SOCIAL_NETWORK = 'TWITTER'
GROUP BY CASE WHEN MEDIA_TYPES IS NULL THEN 'no media' ELSE 'media' END;

-- 8. The most shared tweets (text only: no account is in the data).
SELECT POST_ID, CREATED_TIME, RETWEETS, FAVORITES, SENTIMENT, SUBSTR(MESSAGE, 1, 160) AS MESSAGE
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
WHERE SOCIAL_NETWORK = 'TWITTER'
ORDER BY RETWEETS DESC, POST_ID
LIMIT 10;

-- 9. Which posting apps are used for tweets?
SELECT CLIENT_APP, COUNT(*) AS TWEETS
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
WHERE SOCIAL_NETWORK = 'TWITTER' AND CLIENT_APP IS NOT NULL
GROUP BY CLIENT_APP
ORDER BY TWEETS DESC
LIMIT 10;

-- 10. How often do posts mention treatment words, and how negative are they?
SELECT CASE WHEN LOWER(MESSAGE) LIKE '%chemo%' THEN 'chemotherapy'
            WHEN LOWER(MESSAGE) LIKE '%surgery%' OR LOWER(MESSAGE) LIKE '%esophagectomy%' THEN 'surgery'
            WHEN LOWER(MESSAGE) LIKE '%radiotherapy%' OR LOWER(MESSAGE) LIKE '%radiation%' THEN 'radiation'
            ELSE 'none of these' END AS MENTIONS,
       COUNT(*) AS POSTS, ROUND(100 * AVG(IS_NEGATIVE), 1) AS NEGATIVE_PCT
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
GROUP BY 1
ORDER BY POSTS DESC;

-- 11. Average message length by source.
SELECT SOCIAL_NETWORK, ROUND(AVG(LENGTH(MESSAGE))) AS AVG_CHARS, COUNT(*) AS POSTS
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
WHERE MESSAGE IS NOT NULL
GROUP BY SOCIAL_NETWORK
ORDER BY AVG_CHARS DESC;

-- 12. Replies against original posts, by sentiment.
SELECT IS_REPLY, SENTIMENT, COUNT(*) AS POSTS
FROM ESOPHAGEAL.ESOPHAGEAL_POSTS
GROUP BY IS_REPLY, SENTIMENT
ORDER BY IS_REPLY, POSTS DESC;
