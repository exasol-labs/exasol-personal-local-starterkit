-- examples.sql - questions the amazon_sales dataset answers, one query each.
-- Every query runs as it stands against the loaded AMAZON schema (the kit's tests
-- run them all). Read-only: the MCP user can run them too.

-- 1. How many order lines were cancelled?
SELECT CANCELLED, COUNT(*) AS ORDER_LINES, ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 1) AS PCT
FROM AMAZON.ORDER_LINES
GROUP BY CANCELLED
ORDER BY CANCELLED;

-- 2. Revenue by product category.
SELECT CATEGORY, COUNT(*) AS ORDER_LINES, ROUND(SUM(AMOUNT), 0) AS REVENUE_INR
FROM AMAZON.ORDER_LINES
WHERE CANCELLED = 0
GROUP BY CATEGORY
ORDER BY REVENUE_INR DESC;

-- 3. Which states order most?
SELECT SHIP_STATE, COUNT(*) AS ORDER_LINES, ROUND(SUM(AMOUNT), 0) AS REVENUE_INR
FROM AMAZON.ORDER_LINES
WHERE CANCELLED = 0 AND SHIP_STATE IS NOT NULL
GROUP BY SHIP_STATE
ORDER BY REVENUE_INR DESC
LIMIT 10;

-- 4. Is cancellation more common when the merchant ships?
SELECT FULFILMENT, COUNT(*) AS ORDER_LINES, ROUND(100 * AVG(CANCELLED), 1) AS CANCELLED_PCT
FROM AMAZON.ORDER_LINES
GROUP BY FULFILMENT
ORDER BY CANCELLED_PCT DESC;

-- 5. Sales by week.
SELECT TRUNC(ORDER_DATE, 'IW') AS WEEK_START, COUNT(*) AS ORDER_LINES, ROUND(SUM(AMOUNT), 0) AS REVENUE_INR
FROM AMAZON.ORDER_LINES
WHERE CANCELLED = 0
GROUP BY 1
ORDER BY 1;

-- 6. Cancellation rate by product category.
SELECT CATEGORY, COUNT(*) AS ORDER_LINES, ROUND(100 * AVG(CANCELLED), 1) AS CANCELLED_PCT
FROM AMAZON.ORDER_LINES
GROUP BY CATEGORY
ORDER BY CANCELLED_PCT DESC;

-- 7. Which sizes sell most?
SELECT SIZE, COUNT(*) AS ORDER_LINES
FROM AMAZON.ORDER_LINES
WHERE CANCELLED = 0
GROUP BY SIZE
ORDER BY ORDER_LINES DESC;

-- 8. Every status, with how many lines it holds.
SELECT STATUS, COUNT(*) AS ORDER_LINES
FROM AMAZON.ORDER_LINES
GROUP BY STATUS
ORDER BY ORDER_LINES DESC;

-- 9. The ten best-selling styles.
SELECT STYLE_CODE, COUNT(*) AS ORDER_LINES, ROUND(SUM(AMOUNT), 0) AS REVENUE_INR
FROM AMAZON.ORDER_LINES
WHERE CANCELLED = 0
GROUP BY STYLE_CODE
ORDER BY REVENUE_INR DESC
LIMIT 10;

-- 10. Do promotions go with fewer cancellations?
SELECT HAS_PROMOTION, COUNT(*) AS ORDER_LINES, ROUND(100 * AVG(CANCELLED), 1) AS CANCELLED_PCT
FROM AMAZON.ORDER_LINES
GROUP BY HAS_PROMOTION
ORDER BY HAS_PROMOTION;

-- 11. Average order line value by shipping speed.
SELECT SHIP_SERVICE_LEVEL, COUNT(*) AS ORDER_LINES, ROUND(AVG(AMOUNT), 0) AS AVG_AMOUNT_INR
FROM AMAZON.ORDER_LINES
WHERE CANCELLED = 0
GROUP BY SHIP_SERVICE_LEVEL;

-- 12. Business buyers against the rest.
SELECT IS_B2B, COUNT(*) AS ORDER_LINES, ROUND(AVG(AMOUNT), 0) AS AVG_AMOUNT_INR
FROM AMAZON.ORDER_LINES
WHERE CANCELLED = 0
GROUP BY IS_B2B
ORDER BY IS_B2B;

-- 13. Orders with more than one line.
SELECT COUNT(*) AS MULTI_LINE_ORDERS
FROM (SELECT ORDER_ID FROM AMAZON.ORDER_LINES GROUP BY ORDER_ID HAVING COUNT(*) > 1) AS T;
