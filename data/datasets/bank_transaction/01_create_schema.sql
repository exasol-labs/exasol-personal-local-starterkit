-- 01_create_schema.sql - bank transaction dataset schema.
-- One table, BANK_TRANSACTION.BANK_TRANSACTIONS, from data/bank_transactions.csv:
-- one row per transaction. Idempotent: CREATE OR REPLACE TABLE can be re-run.

CREATE SCHEMA IF NOT EXISTS BANK_TRANSACTION;
OPEN SCHEMA BANK_TRANSACTION;

CREATE OR REPLACE TABLE BANK_TRANSACTIONS (
    TRANSACTION_ID            VARCHAR(20)   NOT NULL,
    ACCOUNT_ID                VARCHAR(20)   NOT NULL,
    TRANSACTION_AMOUNT        DECIMAL(14,2) NOT NULL,
    TRANSACTION_DATE          TIMESTAMP     NOT NULL,
    TRANSACTION_TYPE          VARCHAR(10)   NOT NULL,
    LOCATION                  VARCHAR(50)   NOT NULL,
    DEVICE_ID                 VARCHAR(20)   NOT NULL,
    MERCHANT_ID               VARCHAR(20)   NOT NULL,
    CHANNEL                   VARCHAR(20)   NOT NULL,
    CUSTOMER_AGE              DECIMAL(3,0)  NOT NULL,
    CUSTOMER_OCCUPATION       VARCHAR(30)   NOT NULL,
    TRANSACTION_DURATION      DECIMAL(9,0)  NOT NULL,
    LOGIN_ATTEMPTS            DECIMAL(5,0)  NOT NULL,
    ACCOUNT_BALANCE           DECIMAL(14,2) NOT NULL,
    PREVIOUS_TRANSACTION_DATE TIMESTAMP     NOT NULL,
    CONSTRAINT BANK_TRANSACTIONS_PK PRIMARY KEY (TRANSACTION_ID)
);

COMMENT ON TABLE  BANK_TRANSACTIONS IS 'One bank transaction (2,512 rows). PK transaction_id.';
COMMENT ON COLUMN BANK_TRANSACTIONS.TRANSACTION_ID IS 'Transaction id (PK)';
COMMENT ON COLUMN BANK_TRANSACTIONS.ACCOUNT_ID IS 'Account the transaction is on';
COMMENT ON COLUMN BANK_TRANSACTIONS.TRANSACTION_AMOUNT IS 'Amount moved';
COMMENT ON COLUMN BANK_TRANSACTIONS.TRANSACTION_DATE IS 'When it happened';
COMMENT ON COLUMN BANK_TRANSACTIONS.TRANSACTION_TYPE IS 'Debit or Credit';
COMMENT ON COLUMN BANK_TRANSACTIONS.LOCATION IS 'City where it happened';
COMMENT ON COLUMN BANK_TRANSACTIONS.DEVICE_ID IS 'Device used';
COMMENT ON COLUMN BANK_TRANSACTIONS.MERCHANT_ID IS 'Merchant paid or paying';
COMMENT ON COLUMN BANK_TRANSACTIONS.CHANNEL IS 'ATM, Branch or Online';
COMMENT ON COLUMN BANK_TRANSACTIONS.CUSTOMER_AGE IS 'Account holder age in years';
COMMENT ON COLUMN BANK_TRANSACTIONS.CUSTOMER_OCCUPATION IS 'Account holder occupation';
COMMENT ON COLUMN BANK_TRANSACTIONS.TRANSACTION_DURATION IS 'Seconds the transaction took';
COMMENT ON COLUMN BANK_TRANSACTIONS.LOGIN_ATTEMPTS IS 'Login attempts before it';
COMMENT ON COLUMN BANK_TRANSACTIONS.ACCOUNT_BALANCE IS 'Balance after it';
COMMENT ON COLUMN BANK_TRANSACTIONS.PREVIOUS_TRANSACTION_DATE IS 'When the account last transacted';
