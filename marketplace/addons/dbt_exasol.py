"""dbt-exasol add-on lifecycle, shared by macOS, Linux and Windows.

The generated command wrapper is an installation artifact, not platform
source. All decisions, safety checks and profile rendering live here.
"""

from __future__ import annotations

import importlib.metadata
import json
import os
import shlex
import shutil
import socket
import subprocess
import sys
import tempfile
from pathlib import Path

from runtime import AddonFailure, KitContext, venv_executable, venv_python

ID = "dbt-exasol"
PACKAGE = "dbt-exasol"
RECEIPT = "components.dbt_exasol"


def paths(ctx: KitContext) -> tuple[Path, Path, Path]:
    return (ctx.owned_path(RECEIPT, "venv", "EXAKIT_DBT_EXASOL_VENV", ctx.home / "dbt-exasol-venv"),
            ctx.owned_path(RECEIPT, "profiles_dir", "EXAKIT_DBT_EXASOL_HOME", ctx.home / "dbt"),
            ctx.owned_path(RECEIPT, "command", "EXAKIT_DBT_EXASOL_BIN", ctx.bin_dir / ("dbt-exasol.cmd" if os.name == "nt" else "dbt-exasol")))


def package_version(ctx: KitContext) -> str | None:
    venv, _, _ = paths(ctx)
    python = venv_python(venv)
    if not python.is_file():
        return None
    result = subprocess.run([str(python), "-c", "from importlib.metadata import version; print(version('dbt-exasol'))"],
                            capture_output=True, text=True, check=False, timeout=15)
    return result.stdout.strip() if result.returncode == 0 else None


def installed_version(ctx: KitContext) -> str | None:
    return package_version(ctx) if ctx.manifest.get(f"{RECEIPT}.version") else None


def system_present(ctx: KitContext) -> bool:
    if ctx.manifest.get(f"{RECEIPT}.version"):
        return False
    venv, _, _ = paths(ctx)
    dbt = shutil.which("dbt")
    if dbt and not Path(dbt).is_relative_to(ctx.home):
        try:
            result = subprocess.run([dbt, "--version"], capture_output=True, text=True,
                                    check=False, timeout=10)
            if result.returncode == 0 and "exasol" in (result.stdout + result.stderr).lower():
                return True
        except OSError:
            pass
    if Path(sys.executable).is_relative_to(ctx.home) or Path(sys.executable).is_relative_to(venv):
        return False
    try:
        importlib.import_module("dbt.adapters.exasol")
    except ImportError:
        return False
    return True


def _profile_text(ctx: KitContext) -> str:
    dsn = ctx.manifest.get("runtime.dsn", "")
    user = ctx.manifest.get("runtime.user", "")
    profile = os.environ.get("EXAKIT_DBT_EXASOL_PROFILE", "exasol_starter_kit")
    schema = os.environ.get("EXAKIT_DBT_EXASOL_SCHEMA", "DBT")
    if not all(isinstance(value, str) and value and "\n" not in value for value in (dsn, user, profile, schema)):
        raise AddonFailure("The database connection record is incomplete; run exakit status")
    # JSON strings are valid YAML scalars and safely quote punctuation in DSNs.
    return (
        "# Generated by the Exasol Personal Local Starter Kit; regenerated on update.\n"
        f"{json.dumps(profile)}:\n"
        "  target: dev\n  outputs:\n    dev:\n      type: exasol\n      threads: 1\n"
        f"      dsn: {json.dumps(dsn)}\n      user: {json.dumps(user)}\n"
        "      password: \"{{ env_var('DBT_ENV_SECRET_EXASOL_PASSWORD') }}\"\n"
        f"      dbname: DB\n      schema: {json.dumps(schema)}\n"
        "      encryption: true\n      validate_server_certificate: false\n"
    )


def _write_profile(ctx: KitContext) -> Path:
    _, profile_dir, _ = paths(ctx)
    profile_dir.mkdir(parents=True, exist_ok=True)
    target = profile_dir / "profiles.yml"
    target.write_text(_profile_text(ctx), encoding="utf-8")
    if os.name != "nt":
        target.chmod(0o600)
    return target


def _write_launcher(ctx: KitContext) -> Path:
    venv, profile_dir, launcher = paths(ctx)
    credential = ctx.manifest.get("runtime.password_file", "")
    if not isinstance(credential, str) or not credential:
        raise AddonFailure("The database credential record is incomplete; run exakit status")
    ctx.bin_dir.mkdir(parents=True, exist_ok=True)
    dbt = venv_executable(venv, "dbt")
    if os.name == "nt":
        # Windows needs a .cmd entry point. It only starts the same Python code
        # used by every platform; the credential never appears in an argument.
        launcher.write_text(f'@echo off\r\n"{venv_python(venv)}" "{ctx.root / "marketplace" / "dbt_launcher.py"}" %*\r\n', encoding="utf-8")
    else:
        launcher.write_text("#!/bin/sh\nexec " + shlex.quote(str(venv_python(venv))) + " "
                            + shlex.quote(str(ctx.root / "marketplace" / "dbt_launcher.py")) + ' "$@"\n',
                            encoding="utf-8")
        launcher.chmod(0o755)
    # The launcher reads paths from the kit manifest at use time. A database
    # refresh needs no wrapper rewrite and never embeds a password.
    if not dbt.is_file():
        raise AddonFailure("The dbt executable is missing after installation")
    return launcher


def install(ctx: KitContext, *, force: bool = False) -> None:
    from model import load_addons

    if ctx.manifest.get(f"{RECEIPT}.ownership") in ("user", "unknown"):
        return
    if system_present(ctx):
        return  # Reuse the user's adapter; never claim or replace it.
    ctx.require_uv()
    default = next(item.default_version for item in load_addons(ctx.root) if item.id == ID)
    version = ctx.target_version(ID, default)
    venv, profile_dir, launcher = paths(ctx)
    if package_version(ctx) != version or force:
        if not venv_python(venv).is_file():
            ctx.run_logged("Creating dbt-exasol environment", str(ctx.uv), "venv", "--python", ctx.managed_python_version, str(venv))
        ctx.run_logged(f"Installing dbt-exasol {version}", str(ctx.uv), "pip", "install", "--python",
                       str(venv_python(venv)), f"{PACKAGE}=={version}")
        if package_version(ctx) != version:
            raise AddonFailure("dbt-exasol did not report the requested version after installation")
    _write_profile(ctx)
    _write_launcher(ctx)
    ctx.manifest.set_many({
        f"{RECEIPT}.version": version,
        f"{RECEIPT}.venv": str(venv),
        f"{RECEIPT}.python": str(venv_python(venv)),
        f"{RECEIPT}.command": str(launcher),
        f"{RECEIPT}.profiles_dir": str(profile_dir),
        f"{RECEIPT}.profile": os.environ.get("EXAKIT_DBT_EXASOL_PROFILE", "exasol_starter_kit"),
        f"{RECEIPT}.ownership": "kit",
    })
    if not validate(ctx):
        raise AddonFailure("dbt-exasol validation did not pass; retry with exakit update dbt-exasol")


def validate(ctx: KitContext) -> bool:
    venv, profile_dir, _ = paths(ctx)
    python = venv_python(venv)
    probe = subprocess.run([str(python), "-c", "import dbt.adapters.exasol"],
                           capture_output=True, check=False, timeout=15)
    if probe.returncode != 0:
        ctx.manifest.set_many({f"{RECEIPT}.validated": False})
        return False
    dsn = ctx.manifest.get("runtime.dsn", "")
    try:
        host, port = str(dsn).rsplit(":", 1)
        with socket.create_connection((host or "127.0.0.1", int(port)), timeout=2):
            pass
    except (ValueError, OSError):
        ctx.manifest.set_many({f"{RECEIPT}.validated": True, f"{RECEIPT}.validated_by": "import"})
        return True
    credential = ctx.manifest.get("runtime.password_file", "")
    if not credential or not Path(credential).is_file():
        ctx.manifest.set_many({f"{RECEIPT}.validated": False, f"{RECEIPT}.validated_by": "connection"})
        return False
    with tempfile.TemporaryDirectory(prefix="exakit-dbt-probe-") as temp:
        project = Path(temp) / "dbt_project.yml"
        profile = os.environ.get("EXAKIT_DBT_EXASOL_PROFILE", "exasol_starter_kit")
        project.write_text(f'name: exakit_probe\nversion: "1.0.0"\nconfig-version: 2\nprofile: {json.dumps(profile)}\n')
        env = dict(os.environ)
        env["DBT_ENV_SECRET_EXASOL_PASSWORD"] = Path(credential).read_text(encoding="utf-8").strip()
        env["DBT_PROFILES_DIR"] = str(profile_dir)
        try:
            ctx.run_logged("Checking dbt database connection", str(venv_executable(venv, "dbt")),
                           "debug", "--connection", cwd=Path(temp), env=env, timeout=60)
        except AddonFailure:
            ctx.manifest.set_many({f"{RECEIPT}.validated": False, f"{RECEIPT}.validated_by": "connection"})
            return False
    ctx.manifest.set_many({f"{RECEIPT}.validated": True, f"{RECEIPT}.validated_by": "connection"})
    return True


def update(ctx: KitContext) -> None:
    if ctx.manifest.get(f"{RECEIPT}.ownership") != "kit":
        raise AddonFailure("dbt-exasol is not kit-owned; its owner manages updates")
    install(ctx)
    ctx.manifest.set_many({"desired.dbt_exasol": ctx.manifest.get(f"{RECEIPT}.version")})


def summary(ctx: KitContext) -> str:
    return "build SQL models: dbt-exasol"


def uninstall(ctx: KitContext, *, dry_run: bool = False) -> list[Path]:
    if ctx.manifest.get(f"{RECEIPT}.ownership") != "kit":
        raise AddonFailure("dbt-exasol is not kit-owned; it will not be removed")
    venv, profile_dir, launcher = paths(ctx)
    targets = [venv, launcher, profile_dir / "profiles.yml"]
    if dry_run:
        return [target for target in targets if target.exists()]
    if venv.exists():
        shutil.rmtree(venv)
    launcher.unlink(missing_ok=True)
    (profile_dir / "profiles.yml").unlink(missing_ok=True)
    try:
        profile_dir.rmdir()
    except OSError:
        pass
    ctx.manifest.delete(RECEIPT, "desired.dbt_exasol")
    return targets
