"""Prepare a governed Dash Server dashboard and promote only a reviewed preview.

``tool`` is a callable for the registered dash-server MCP tools. Agents pass their
MCP tool adapter; notebooks can export the exact requests for an agent to run.
The dashboard itself queries Exasol through Dash Server's server-side profile.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from dataclasses import dataclass
from typing import Any, Callable

from .ask import _read_sql
from .workflow import DASHBOARD_REVISION, current_workflow, home, log_event

Tool = Callable[[str, dict[str, Any]], dict[str, Any]]
_NAME = re.compile(r"^[a-z][a-z0-9-]*$")


def _unwrap(result: dict[str, Any]) -> dict[str, Any]:
    if result.get("isError") or result.get("is_error"):
        raise RuntimeError("Dash Server refused the request: " + str(result.get("content", "error"))[:500])
    return result.get("structuredContent") or result.get("structured_content") or result


def _app_source(title: str, metadata: dict[str, str]) -> str:
    # The helper is generated by Dash Server's Exasol scaffold and reads its
    # server-side profile. The uploaded app contains no connection credentials.
    return '''import importlib.util
from pathlib import Path

import plotly.graph_objects as go
from dash import Dash, Input, Output, dcc, html

spec = importlib.util.spec_from_file_location("dash_server_generated_exasol_helper", Path(__file__).with_name("dash_server_exasol.py"))
helper = importlib.util.module_from_spec(spec)
spec.loader.exec_module(helper)
load_rows = helper.load_rows
render_table = helper.render_table
has_error = helper.has_error

TITLE = ''' + repr(title) + '''
LINEAGE = ''' + repr(metadata) + '''

def create_dash_app(server, url_base_pathname, metadata):
    app = Dash(__name__, server=server, routes_pathname_prefix="/",
               requests_pathname_prefix=url_base_pathname.rstrip("/") + "/",
               title=metadata.get("title", TITLE))
    app.layout = html.Main([
        html.H1(TITLE),
        html.P("Live Exasol result. Verify figures against the approved SQL."),
        html.P("Descriptor " + LINEAGE["descriptor_version"] + " · Query " + LINEAGE["query_digest"][:12]),
        dcc.Interval(id="refresh", interval=30000, n_intervals=0),
        dcc.Graph(id="result-chart"),
        html.Div(id="result-table"),
    ], style={"fontFamily": "sans-serif", "maxWidth": "1100px", "margin": "2rem auto"})

    @app.callback(Output("result-chart", "figure"), Output("result-table", "children"), Input("refresh", "n_intervals"))
    def refresh(_):
        rows = load_rows(server, metadata, __file__, "queries/business/result.sql")
        figure = go.Figure()
        if has_error(rows):
            figure.add_annotation(text=str(rows[0]["_error"]), showarrow=False)
            return figure, html.Pre(str(rows[0]["_error"]))
        if rows:
            keys = list(rows[0])
            if len(keys) >= 2 and all(isinstance(row.get(keys[1]), (int, float)) for row in rows):
                figure.add_bar(x=[str(row.get(keys[0], "")) for row in rows[:50]],
                               y=[row[keys[1]] for row in rows[:50]])
        if not figure.data:
            figure.add_annotation(text="No numeric series; inspect the table below.", showarrow=False)
        figure.update_layout(xaxis_title="Category", yaxis_title="Value")
        return figure, render_table(rows[:1000])
    return app
'''


@dataclass
class ShareDraft:
    dataset: Any
    sql: str
    title: str
    name: str
    query_digest: str
    files: list[dict[str, str]]
    revision_number: int | None = None
    preview_url: str | None = None
    healthy: bool = False

    def requests(self, profile_name: str = "starter-kit") -> list[tuple[str, dict[str, Any]]]:
        """The exact MCP calls an agent makes to create the preview (no credentials)."""
        return [
            ("app_create_exasol_dashboard", {"name": self.name, "profile_name": profile_name,
                                             "pattern": "analytics-hub", "title": self.title,
                                             "start_immediately": False}),
            ("app_put_files", {"name": self.name, "files": self.files}),
            ("app_deploy_draft", {"name": self.name, "deployment_target": "preview"}),
            ("app_run_healthcheck", {"name": self.name, "target": "preview"}),
        ]

    def preview(self, tool: Tool, profile_name: str = "starter-kit", windows: bool | None = None) -> str:
        """Create and health-check a preview; on Windows use build + healthcheck."""
        manifest = json.loads((home() / "manifest.json").read_text(encoding="utf-8"))
        readonly = manifest["components"]["mcp_server"]["connection"]
        if readonly.get("validated") is not True or not readonly.get("user"):
            raise RuntimeError("The read-only identity is not validated. Run exakit mcp-doctor.")
        profile = _unwrap(tool("exasol_profile_validate", {"name": profile_name}))
        bound = profile.get("profile", {})
        if (not profile.get("is_valid") or bound.get("user", "").upper() != readonly["user"].upper()
                or bound.get("dsn") != manifest["runtime"]["dsn"]):
            raise RuntimeError("Dash Server profile must validate as the kit's read-only user and database. Run exakit mcp-setup and restart dash-server.")
        if windows is None:
            windows = sys.platform == "win32"
        requests = self.requests(profile_name)
        for method, params in requests[:2]:
            _unwrap(tool(method, params))
        if windows:
            built = _unwrap(tool("app_build", {"name": self.name}))
            revision = built.get("revision", {}).get("revision_number")
            if not isinstance(revision, int):
                raise RuntimeError("Dash Server build did not return a revision number.")
            self.revision_number = revision
            deployed = _unwrap(tool("app_start_preview", {"name": self.name, "revision_number": revision}))
        else:
            deployed = _unwrap(tool(*requests[2]))
            self.revision_number = deployed.get("build", {}).get("revision", {}).get("revision_number")
        if not isinstance(self.revision_number, int):
            raise RuntimeError("Dash Server did not return a preview revision number.")
        checked = _unwrap(tool(*requests[3]))
        if checked.get("health", {}).get("status") != "healthy":
            raise RuntimeError("Dash Server preview is unhealthy; inspect its health check before publishing.")
        self.healthy = True
        app = deployed.get("app", {})
        self.preview_url = app.get("preview_path") or f"/preview/{self.name}/{self.revision_number}"
        log_event(DASHBOARD_REVISION, app=self.name, revision=self.revision_number,
                  descriptor_id=self.dataset.id, descriptor_version=self.dataset.version,
                  query_digest=self.query_digest, workflow_id=current_workflow(), state="preview")
        return self.preview_url

    def confirm(self, tool: Tool, figures_checked: bool = False) -> str:
        """Promote the exact healthy preview after a human checks its figures."""
        if not figures_checked or not self.healthy or self.revision_number is None:
            raise RuntimeError("Open the healthy preview, verify the figures against the SQL, then confirm with figures_checked=True.")
        promoted = _unwrap(tool("app_promote_revision", {"name": self.name,
            "revision_number": self.revision_number, "require_healthy": True}))
        if not promoted.get("app", {}).get("mounted"):
            _unwrap(tool("app_start", {"name": self.name}))
        checked = _unwrap(tool("app_run_healthcheck", {"name": self.name, "target": "live"}))
        if checked.get("health", {}).get("status") != "healthy":
            raise RuntimeError("The live dashboard failed its health check; use app_rollback in Dash Server.")
        log_event(DASHBOARD_REVISION, app=self.name, revision=self.revision_number,
                  descriptor_id=self.dataset.id, descriptor_version=self.dataset.version,
                  query_digest=self.query_digest, workflow_id=current_workflow(), state="live")
        return promoted.get("app", {}).get("route") or f"/apps/{self.name}"


def share(dataset: Any, sql: str, title: str, name: str) -> ShareDraft:
    """Make a draft from approved data and an inspected read-only SQL query."""
    dataset.require_approved("share")
    if not _NAME.fullmatch(name):
        raise ValueError("Dashboard name must use lowercase letters, numbers and hyphens, starting with a letter.")
    if not title.strip():
        raise ValueError("Give the dashboard a title.")
    statement = _read_sql(sql)
    digest = hashlib.sha256(statement.encode("utf-8")).hexdigest()
    lineage = {"workflow_id": current_workflow() or "none", "descriptor_id": dataset.id,
               "descriptor_version": str(dataset.version), "query_digest": digest}
    print("Dashboard SQL to validate against its figures:\n" + statement)
    files = [
        {"path": "app.py", "content": _app_source(title.strip(), lineage)},
        {"path": "queries/business/result.sql", "content": statement + "\n"},
        {"path": "REVISION.json", "content": json.dumps(lineage, indent=2) + "\n"},
    ]
    return ShareDraft(dataset, statement, title.strip(), name, digest, files)
