"""Prepare a governed Dash Server dashboard and promote only a reviewed preview.

``tool`` is a callable for the registered dash-server MCP tools. Notebook cells
use the kit-managed MCP endpoint through ``dash_tools()``.
The dashboard itself queries Exasol through Dash Server's server-side profile.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from dataclasses import dataclass
from typing import Any, Callable

from .ask import _read_sql
from .workflow import DASHBOARD_REVISION, current_workflow, home, log_event

Tool = Callable[[str, dict[str, Any]], dict[str, Any]]
_NAME = re.compile(r"^[a-z][a-z0-9-]*$")


def _unwrap(result: dict[str, Any]) -> dict[str, Any]:
    if result.get("isError") or result.get("is_error"):
        raise RuntimeError("Dash Server refused the request: " + str(result.get("content", "error"))[:500])
    return result.get("structuredContent") or result.get("structured_content") or result


def _app_source(title: str, metadata: dict[str, str], app: str | None = None) -> str:
    # The helper is generated by Dash Server's Exasol scaffold and reads its
    # server-side profile. The uploaded app contains no connection credentials.
    from .share_template import APP_SOURCE
    if app is not None and "def create_dash_app" not in str(app):
        raise ValueError("Your dashboard source must keep create_dash_app(server, url_base_pathname, metadata): Dash Server calls it.")
    template = APP_SOURCE if app is None else str(app)
    template = re.sub(r"^TITLE = ''$", lambda _: "TITLE = " + repr(title), template, flags=re.M)
    return re.sub(r"^LINEAGE = \{\}$", lambda _: "LINEAGE = " + repr(metadata), template, flags=re.M)


@dataclass
class ShareDraft:
    """A dashboard prepared from an approved dataset and one query. ``preview()`` puts it on Dash Server as a preview;
    ``confirm(..., figures_checked=True)`` publishes it, and only after a person checked the preview's figures."""

    dataset: Any
    sql: str
    title: str
    name: str
    query_digest: str
    workflow_id: str
    files: list[dict[str, str]]
    revision_number: int | None = None
    preview_url: str | None = None
    healthy: bool = False

    def requests(self, profile_name: str = "starter-kit") -> list[tuple[str, dict[str, Any]]]:
        """The exact MCP calls an agent makes to create the preview (no credentials)."""
        return [
            ("app_create_exasol_dashboard", {"name": self.name, "profile_name": profile_name,
                                             "pattern": "analytics-hub", "title": self.title,
                                             "description": self.description(),
                                             "start_immediately": False}),
            ("app_put_files", {"name": self.name, "files": self.files}),
            ("app_deploy_draft", {"name": self.name, "deployment_target": "preview"}),
            ("app_run_healthcheck", {"name": self.name, "target": "preview"}),
        ]

    def _owns(self, lineage: dict[str, Any]) -> bool:
        """An app already on Dash Server under this name is this notebook's to replace: its lineage is this data's."""
        return (lineage.get("descriptor_id") == self.dataset.id
                and all(lineage.get(key) for key in ("workflow_id", "descriptor_version", "query_digest")))

    def _logged(self) -> dict[str, Any]:
        return {"descriptor_id": self.dataset.id, "descriptor_version": self.dataset.version,
                "query_digest": self.query_digest, "sql": self.sql, "source_table": getattr(self.dataset, "fact_table", None)}

    def description(self) -> str:
        """The catalog's line under the title: the approved data it answers from. Without one Dash Server writes
        "Live Exasol dashboard backed by profile <name>", which says nothing about the dashboard."""
        return f"From the approved {self.dataset.id} data, descriptor v{self.dataset.version}."

    def preview(self, tool: Tool, profile_name: str = "starter-kit", windows: bool | None = None) -> str:
        """Create and health-check a preview; on Windows use build + healthcheck."""
        self.healthy = False
        self.revision_number = None
        self.preview_url = None
        if current_workflow() != self.workflow_id:
            raise RuntimeError(f"Resume workflow {self.workflow_id} before previewing this dashboard.")
        manifest = json.loads((home() / "manifest.json").read_text(encoding="utf-8"))
        readonly = (manifest.get("components", {}).get("mcp_server") or {}).get("connection") or {}
        admin = manifest.get("runtime", {}).get("user", "")
        if (readonly.get("validated") is not True or not readonly.get("user")
                or readonly["user"].upper() == admin.upper()):
            raise RuntimeError("The read-only identity is not validated. Run exakit mcp-doctor.")
        profile = _unwrap(tool("exasol_profile_validate", {"name": profile_name}))
        bound = profile.get("profile", {})
        # The profile may hold the database's address with its TLS pin (HOST/<sha256>:PORT, after exakit start pins
        # the certificate): the same database as the manifest's plain HOST:PORT, so both forms are the kit's.
        plain = manifest.get("runtime", {}).get("dsn")
        from ._kit import pinned_dsn, tls_fingerprint

        kit_dsns = {plain, pinned_dsn(plain, tls_fingerprint())} if plain else set()
        if (not profile.get("is_valid") or bound.get("user", "").upper() != readonly["user"].upper()
                or bound.get("dsn") not in kit_dsns):
            raise RuntimeError("Dash Server profile must validate as the kit's read-only user and database. Run exakit mcp-setup and restart dash-server.")
        if windows is None:
            windows = sys.platform == "win32"
        requests = self.requests(profile_name)
        created = tool(*requests[0])
        if created.get("isError") or created.get("is_error"):
            category = (created.get("structuredContent") or created.get("structured_content") or {}).get("error", {}).get("category")
            if category != "app_conflict":
                _unwrap(created)
            # Put files changes only the draft. Before touching an existing
            # workspace, prove that this notebook owns its lineage and that it
            # belongs to the same approved dataset.
            try:
                saved = _unwrap(tool("app_read_file", {"name": self.name, "path": "REVISION.json"}))
                lineage = json.loads(saved["content"])
            except (KeyError, TypeError, ValueError, RuntimeError) as error:
                raise RuntimeError(f"Dashboard {self.name} already exists without readable starter-kit lineage; choose another APP_NAME.") from error
            if not isinstance(lineage, dict) or not self._owns(lineage):
                raise RuntimeError(f"Dashboard {self.name} belongs to a different dataset or has incomplete lineage; choose another APP_NAME.")
        _unwrap(tool(*requests[1]))
        if windows:
            built = _unwrap(tool("app_build", {"name": self.name}))
            revision = built.get("revision", {}).get("revision_number")
            if not isinstance(revision, int):
                raise RuntimeError("Dash Server build did not return a revision number.")
            revision_number = revision
            deployed = _unwrap(tool("app_start_preview", {"name": self.name, "revision_number": revision}))
        else:
            deployed = _unwrap(tool(*requests[2]))
            revision_number = deployed.get("build", {}).get("revision", {}).get("revision_number")
        if not isinstance(revision_number, int):
            raise RuntimeError("Dash Server did not return a preview revision number.")
        compared = _unwrap(tool("app_diff_draft_vs_artifact", {"name": self.name,
            "revision_number": revision_number}))
        snapshotted = {row.get("path"): row.get("status") for row in compared.get("files", [])}
        if any(snapshotted.get(path) != "unchanged" for path in
               (row["path"] for row in self.files)):
            raise RuntimeError("The built Dash Server revision does not contain the approved SQL and lineage files unchanged.")
        checked = _unwrap(tool(*requests[3]))
        if checked.get("health", {}).get("status") != "healthy":
            raise RuntimeError("Dash Server preview is unhealthy; inspect its health check before publishing.")
        self.revision_number = revision_number
        self.healthy = True
        app = deployed.get("app", {})
        self.preview_url = app.get("preview_path") or f"/preview/{self.name}/{self.revision_number}"
        log_event(DASHBOARD_REVISION, app=self.name, revision=self.revision_number, **self._logged(),
                  preview_path=self.preview_url, state="preview")
        return self.preview_url

    def confirm(self, tool: Tool, figures_checked: bool = False) -> str:
        """Promote the exact healthy preview after a human checks its figures."""
        if current_workflow() != self.workflow_id:
            raise RuntimeError(f"Resume workflow {self.workflow_id} before promoting this dashboard.")
        if not figures_checked or not self.healthy or self.revision_number is None:
            raise RuntimeError("Open the healthy preview, verify the figures against the SQL, then confirm with figures_checked=True.")
        promoted = _unwrap(tool("app_promote_revision", {"name": self.name,
            "revision_number": self.revision_number, "require_healthy": True}))
        if not promoted.get("app", {}).get("mounted"):
            _unwrap(tool("app_start", {"name": self.name}))
        checked = _unwrap(tool("app_run_healthcheck", {"name": self.name, "target": "live"}))
        if checked.get("health", {}).get("status") != "healthy":
            raise RuntimeError("The live dashboard failed its health check; use app_rollback in Dash Server.")
        log_event(DASHBOARD_REVISION, app=self.name, revision=self.revision_number, **self._logged(), state="live")
        return promoted.get("app", {}).get("route") or f"/apps/{self.name}"


def share_app() -> str:
    """The one-query dashboard's own source (app.py), to save, change and give back: nb.share(..., app=your_text).
    Keep create_dash_app, and the TITLE = '' and LINEAGE = {} lines the kit fills in."""
    from .share_template import APP_SOURCE

    return APP_SOURCE


def share(dataset: Any, sql: str, title: str, name: str, *, measure: str = "value", app: str | None = None) -> ShareDraft:
    """Make a draft from approved data and inspected SQL; measure=count enables count totals and composition."""
    if measure not in ("value", "count"):
        raise ValueError("measure must be value or count; only reviewed counts have a share-of-total chart.")
    workflow_id = current_workflow()
    if workflow_id is None:
        raise RuntimeError("Start a workflow with nb.workflow(name) before preparing a dashboard.")
    dataset.require_approved("share")
    if not _NAME.fullmatch(name):
        raise ValueError("Dashboard name must use lowercase letters, numbers and hyphens, starting with a letter.")
    if not title.strip():
        raise ValueError("Give the dashboard a title.")
    statement = _read_sql(sql)
    digest = hashlib.sha256(statement.encode("utf-8")).hexdigest()
    lineage = {"workflow_id": workflow_id, "descriptor_id": dataset.id,
               "descriptor_version": str(dataset.version), "query_digest": digest, "measure": measure}
    print("Dashboard SQL to validate against its figures:\n" + statement)
    from .share_template import APP_CSS
    files = [
        {"path": "app.py", "content": _app_source(title.strip(), lineage, app)},
        {"path": "assets/share.css", "content": APP_CSS},
        {"path": "queries/business/result.sql", "content": statement + "\n"},
        {"path": "REVISION.json", "content": json.dumps(lineage, indent=2) + "\n"},
    ]
    return ShareDraft(dataset, statement, title.strip(), name, digest, workflow_id, files)


@dataclass
class BoardDraft(ShareDraft):
    """A multi-page dashboard made from a board (nb.board): one Dash app, a tab per page, a tile per approved answer.
    Previewed and published like a one-query dashboard: a health-checked preview first, live only after a person
    checked the figures. Its lineage names the board and every tile's approved SQL digest."""

    board: Any = None

    def description(self) -> str:
        pages = self.board.pages
        return (f"{len(pages)} page{'s' if len(pages) != 1 else ''}, {len(self.board.tiles)} approved answers "
                f"({', '.join(p['title'] for p in pages)[:200]}).")

    def _owns(self, lineage: dict[str, Any]) -> bool:
        return lineage.get("board") == self.board.name and bool(lineage.get("workflow_id"))

    def _logged(self) -> dict[str, Any]:
        return {"board": self.board.name, "query_digest": self.query_digest,
                "tiles": [{"id": t["id"], "sql_digest": t["sql_digest"], "dataset": t.get("dataset")} for t in self.board.tiles]}


def board_draft(board: Any, name: str, app: str | None = None) -> BoardDraft:
    """The Dash app of a board: app.py (the tabbed dashboard), BOARD.json (its pages, tiles and filters), one SQL file
    per tile (the approved SQL, unchanged) and REVISION.json (the lineage). Every tile's SQL is shown here first."""
    workflow_id = current_workflow()
    if workflow_id is None:
        raise RuntimeError("Start a workflow with nb.workflow(name) before preparing a dashboard.")
    if not _NAME.fullmatch(name):
        raise ValueError("Dashboard name must use lowercase letters, numbers and hyphens, starting with a letter.")
    if not board.tiles:
        raise ValueError(f"{board.name} has no tiles yet: pin an approved answer to it first (nb.pin).")
    spec = board.spec()
    digest = hashlib.sha256(json.dumps([t["sql_digest"] for t in board.tiles]).encode("utf-8")).hexdigest()
    lineage = {"workflow_id": workflow_id, "board": board.name, "query_digest": digest,
               "tiles": {t["id"]: {"sql_digest": t["sql_digest"], "dataset": t.get("dataset"),
                                   "descriptor_version": t.get("descriptor_version")} for t in board.tiles}}
    from .board_template import BOARD_APP, BOARD_CSS
    from .share_template import APP_CSS

    if app is not None and "def create_dash_app" not in str(app):
        raise ValueError("Your dashboard source must keep create_dash_app(server, url_base_pathname, metadata): Dash Server calls it.")
    source = BOARD_APP if app is None else str(app)
    lineage["app"] = "kit" if app is None else "yours, sha256 " + hashlib.sha256(source.encode("utf-8")).hexdigest()[:16]
    files = [{"path": "app.py", "content": source},
             {"path": "assets/share.css", "content": APP_CSS + BOARD_CSS},
             {"path": "BOARD.json", "content": json.dumps(spec, indent=2) + "\n"},
             {"path": "REVISION.json", "content": json.dumps(lineage, indent=2) + "\n"}]
    for tile in board.tiles:
        statement = _read_sql(tile["sql"])
        if hashlib.sha256(statement.encode("utf-8")).hexdigest() != tile["sql_digest"]:
            raise RuntimeError(f"Tile {tile['id']} ({tile['title']}) no longer matches the SQL that was approved; pin it again.")
        files.append({"path": f"queries/{tile['id']}.sql", "content": statement + "\n"})
        print(f"[{tile['id']}] {tile['title']}\n{statement}\n")
    return BoardDraft(dataset=None, sql="", title=spec["title"], name=name, query_digest=digest, workflow_id=workflow_id,
                      files=files, board=board)
